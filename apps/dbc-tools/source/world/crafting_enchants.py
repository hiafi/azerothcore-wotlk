"""
Crafting rework C6: enchants as items (`.agents/plans/crafting-rework/crafting-rework.C6-RESEARCH.md`, rulings
2026-11-11).

Declares, from the table in `lib/crafting_enchants_data.py`:

- the enchants (`SpellItemEnchantment` 5800-5930): leveling 5800-5857 (no level gate), endgame 5860-5917 (`MinLevel`
  60), the Engineering tinkers 5920-5923 (type 7 USE_SPELL) and the belt buckle 5930 (type 8, a prismatic socket);
- each item's on-use spell (207200-207330): SPELL_EFFECT_ENCHANT_ITEM (53) into the permanent slot, or for the buckle
  SPELL_EFFECT_ADD_SOCKET (156) into the prismatic slot. `Targets` 16 opens the item cursor; the Equipped* masks pick
  the slot the item fits (`Item::IsFitToSpellRequirements`). BaseLevel 0: any item can take it. Row shape copied from
  the stock Brilliant Spellthread 55631 / Eternal Belt Buckle 55655;
- the recipes (207340-207470) on each profession's skill line and their `SkillLineAbility` rows (31020-31145), taught
  by the Azeroth trainer of the profession (Blacksmithing 60, Leatherworking 61, Tailoring 74, Engineering 92,
  Enchanting 96, Inscription 121);
- the four tinker effect spells (207480-207483); Force Field Lens is scripted (`spell_crafting_force_field_lens`,
  `src/server/scripts/Custom/custom_crafting_enchants.cpp`: the absorb is 10% of maximum health).

The items themselves (`item_template` + `items.csv`) are hand-written rows generated by `write_enchant_items.py`.
"""

from lib.dsl import RANGE_SELF, AuraType, Effect, EffectType, School
from lib.dsl.enchants import enchant, socket_effect, spell_effect, stat_effect
from lib.dsl.registry import EnchantType, scripted_by, skill_line_ability, spell, trained_by

from lib import crafting_enchants_data as T

_TEXT_MASKS = {
    'Name_Lang_Mask': 16712190, 'NameSubtext_Lang_Mask': 16712190, 'NameSubtext_Lang_enUS': '',
    'Description_Lang_Mask': 16712190, 'AuraDescription_Lang_Mask': 16712190,
}
_TARGET_UNIT_CASTER = 1
_TARGET_FLAG_ITEM = 16
_EFFECT_CREATE_ITEM = 24
_EFFECT_ENCHANT_ITEM = 53
_EFFECT_ADD_SOCKET = 156
_ATTR0_IS_TRADESKILL_NOT_SHAPESHIFTED = 0x00010020
_ATTR1_NO_THREAT = 0x00000400
_ATTR2_ENCHANT_OWN_ITEM_ONLY = 0x00002000
_INTERRUPT_FLAGS = 15
_CAST_INDEX_APPLY = 15  # the stock thread / inscription / buckle application (3 s)

# Per profession: the stock recipe shape (CastingTimeIndex, SpellVisualID_1, SpellIconID, extra raw columns) and the
# use spell's look (SpellVisualID_1, SpellIconID) per item form.
_CRAFT_SHAPE = {
    T.ENCHANTING: (33, 3182, 241, {}),  # Enchanted Leather 17181, no rod
    T.TAILORING: (38, 1168, 69, {}),  # Mystic Spellthread 31430
    T.LEATHERWORKING: (34, 4439, 1, {}),  # Rugged Armor Kit 19058
    T.ENGINEERING: (38, 395, 1, {'RequiredTotemCategoryID_1': 14}),  # Sniper Scope 12620: Arclight Spanner, no anvil
    T.INSCRIPTION: (5, 10130, 2557, {'RequiredTotemCategoryID_1': 121}),  # the C4 Missives: Virtuoso Inking Set
    T.BLACKSMITHING: (37, 395, 335, {'RequiresSpellFocus': 1, 'RequiredTotemCategoryID_1': 162}),  # Eternal Belt Buckle
}
_USE_LOOK = {
    "scroll": (3182, 241), "kit": (3326, 2474), "spellthread": (1168, 1), "inscription": (4050, 1),
    "lens": (215, 333), "scope": (215, 333), "buckle": (12728, 3105),
}


def _reagent_columns(reagents) -> dict:
    out = {}
    for index, (item, count) in enumerate(reagents, start=1):
        out[f'Reagent_{index}'] = item
        out[f'ReagentCount_{index}'] = count
    return out


def _recipe(spell_id: int, sla_id: int, name: str, item: int, profession: int, reagents, train_cost: int,
            note: str) -> None:
    cast_index, visual, icon, extra = _CRAFT_SHAPE[profession]
    spell(
        id=spell_id, name=name, school=School.NORMAL, attributes=_ATTR0_IS_TRADESKILL_NOT_SHAPESHIFTED, cast_time_ms=0,
        cooldown_ms=0, category_cooldown_ms=0, mana_cost=0, mana_cost_pct=0, range_yards=RANGE_SELF, duration_ms=0,
        effects=[Effect(type=_EFFECT_CREATE_ITEM, implicit_target_a=_TARGET_UNIT_CASTER)], spell_icon_id=icon,
        notes=f'Crafting rework C6: the recipe of {name} (item {item}). {note}',
        raw_overrides={
            'SpellClassSet': 0, 'EquippedItemClass': -1, 'SpellLevel': 0, 'AttributesEx': _ATTR1_NO_THREAT,
            'CastingTimeIndex': cast_index, 'InterruptFlags': _INTERRUPT_FLAGS, 'ProcChance': 101,
            'EffectItemType_1': item, 'SpellVisualID_1': visual, 'Description_Lang_enUS': '',
            'AuraDescription_Lang_enUS': '', **_reagent_columns(reagents), **extra, **_TEXT_MASKS,
        },
    )
    skill_line_ability(id=sla_id, skill_line=profession, spell_id=spell_id, min_skill_line_rank=1, acquire_method=0,
                       raw_overrides={'TrivialSkillLineRankHigh': 1, 'TrivialSkillLineRankLow': 1})
    trained_by(spell_id, T.TRAINER[profession], req_level=0, money_cost=train_cost, req_skill_line=profession,
               req_skill_rank=1)


def _use_spell(spell_id: int, name: str, effect_type: int, enchant_id: int, target, form: str, description: str,
               note: str) -> None:
    item_class, subclass_mask, inv_mask = target
    visual, icon = _USE_LOOK[form]
    spell(
        id=spell_id, name=name, school=School.NORMAL, attributes=0, cast_time_ms=0, cooldown_ms=0,
        category_cooldown_ms=0, mana_cost=0, mana_cost_pct=0, range_yards=RANGE_SELF, duration_ms=0,
        effects=[Effect(type=effect_type, misc_value=enchant_id)], spell_icon_id=icon,
        notes=f'Crafting rework C6: {note}',
        raw_overrides={
            'SpellClassSet': 0, 'SpellLevel': 0, 'BaseLevel': 0, 'AttributesEx2': _ATTR2_ENCHANT_OWN_ITEM_ONLY,
            'Targets': _TARGET_FLAG_ITEM, 'CastingTimeIndex': _CAST_INDEX_APPLY, 'InterruptFlags': _INTERRUPT_FLAGS,
            'ProcChance': 101, 'EquippedItemClass': item_class, 'EquippedItemSubclass': subclass_mask,
            'EquippedItemInvTypes': inv_mask, 'SpellVisualID_1': visual, 'Description_Lang_enUS': description,
            'AuraDescription_Lang_enUS': '', **_TEXT_MASKS,
        },
    )


# --- Basic enchants: leveling and endgame sets ------------------------------------------------------------------------
for _row in T.enchants():
    enchant(_row["enchant"], _row["text"], stat_effect(_row["stat"], _row["amount"]), min_level=_row["min_level"])
    _use_spell(_row["use_spell"], _row["name"], _EFFECT_ENCHANT_ITEM, _row["enchant"], _row["target"], _row["form"],
               _row["description"],
               f'the on-use spell of {_row["name"]} (item {_row["item"]}): enchant {_row["enchant"]} '
               f'({_row["text"]}, {_row["tier"]} {_row["slot"]}).')
    _recipe(_row["craft_spell"], _row["sla"], _row["name"], _row["item"], _row["profession"], _row["reagents"],
            _row["train_cost"], f'{_row["tier"].capitalize()} set, trained.')

# --- Engineering tinkers (endgame) -----------------------------------------------------------------------------------
_CR_CRIT = (1 << 8) | (1 << 9) | (1 << 10)
_CR_HASTE = (1 << 17) | (1 << 18) | (1 << 19)
_SCHOOL_MASK_ALL = 127
_POWER_MANA = 0


def _aura(aura: int, misc: int, amount: int) -> Effect:
    # base_points is the raw DBC column: the effect's value is base_points + 1 (DieSides 1).
    return Effect(type=EffectType.APPLY_AURA, apply_aura=aura, misc_value=misc, base_points=amount - 1,
                  implicit_target_a=_TARGET_UNIT_CASTER)


_TINKER_EFFECTS = {
    "hyperspeed": ([_aura(AuraType.MOD_RATING, _CR_HASTE, T.HYPERSPEED_HASTE)], T.TINKER_BUFF_MS, 3053, 12028,
                   'Haste Rating increased by $s1.'),
    "force_field": ([_aura(AuraType.SCHOOL_ABSORB, _SCHOOL_MASK_ALL, 1)], T.FORCE_FIELD_MS, 566, 12028,
                    'Absorbs damage.'),
    "mana_siphon": ([Effect(type=EffectType.ENERGIZE_PCT, misc_value=_POWER_MANA, base_points=T.MANA_SIPHON_PCT - 1,
                            implicit_target_a=_TARGET_UNIT_CASTER)], 0, 3184, 12028, ''),
    "targeting": ([_aura(AuraType.MOD_RATING, _CR_CRIT, T.TARGETING_CRIT)], T.TINKER_BUFF_MS, 333, 12028,
                  'Critical Strike Rating increased by $s1.'),
}

for _tinker in T.tinkers():
    _effects, _duration, _icon, _visual, _aura_text = _TINKER_EFFECTS[_tinker["key"]]
    _effect_spell = spell(
        id=_tinker["effect_spell"], name=_tinker["name"], school=School.NORMAL, attributes=0, cast_time_ms=0,
        cooldown_ms=_tinker["cooldown_ms"], category_cooldown_ms=T.TINKER_CATEGORY_COOLDOWN_MS, mana_cost=0,
        mana_cost_pct=0, range_yards=RANGE_SELF, duration_ms=_duration, effects=_effects, spell_icon_id=_icon,
        notes=f'Crafting rework C6: the {_tinker["name"]} tinker\'s effect, cast by right-clicking the enchanted '
              f'{_tinker["slot"]} piece (enchant {_tinker["enchant"]}, type 7). Stock tinker category 1141 with its '
              f'10 s category lockout, as Hyperspeed Acceleration 54758.',
        raw_overrides={
            'SpellClassSet': 0, 'EquippedItemClass': -1, 'SpellLevel': 0, 'CastingTimeIndex': 1,
            'Category': T.TINKER_CATEGORY, 'SpellVisualID_1': _visual,
            'Description_Lang_enUS': _tinker["effect_text"], 'AuraDescription_Lang_enUS': _aura_text, **_TEXT_MASKS,
        },
    )
    if _tinker["key"] == "force_field":
        scripted_by(_effect_spell, "spell_crafting_force_field_lens")
    enchant(_tinker["enchant"], _tinker["name"], spell_effect(EnchantType.USE_SPELL, _effect_spell), min_level=60)
    _ranged = _tinker["slot"] == "ranged"
    _use_spell(_tinker["use_spell"], _tinker["name"], _EFFECT_ENCHANT_ITEM, _tinker["enchant"], _tinker["target"],
               "scope" if _ranged else "lens",
               f'Permanently attach the {_tinker["name"]} to a {"bow, gun or crossbow" if _ranged else "helm"}, '
               f'replacing its enchant. The enchanted piece then has: {T.TINKER_ITEM_TEXT[_tinker["key"]]}',
               f'the on-use spell of {_tinker["name"]} (item {_tinker["item"]}): tinker enchant {_tinker["enchant"]}.')
    _recipe(_tinker["craft_spell"], _tinker["sla"], _tinker["name"], _tinker["item"], T.ENGINEERING,
            T.TINKER_REAGENTS, T.TRAIN_COST["endgame"], 'Engineering tinker, trained.')

# --- Blacksmithing belt buckle (endgame) ------------------------------------------------------------------------------
_B = T.BUCKLE
enchant(_B["enchant"], _B["text"], socket_effect(), min_level=60)
_use_spell(_B["use_spell"], _B["name"], _EFFECT_ADD_SOCKET, _B["enchant"],
           (T.ITEM_CLASS_ARMOR, T.ARMOR_ANY, 1 << 6), "buckle", _B["description"],
           f'the on-use spell of {_B["name"]} (item {_B["item"]}): prismatic socket enchant {_B["enchant"]} into the '
           f'prismatic slot, as the stock Eternal Belt Buckle 55655.')
_recipe(_B["craft_spell"], _B["sla"], _B["name"], _B["item"], T.BLACKSMITHING, _B["reagents"],
        T.TRAIN_COST["endgame"], 'Blacksmithing belt buckle, trained.')
