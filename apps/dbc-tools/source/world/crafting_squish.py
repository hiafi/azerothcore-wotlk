_REAGENT_SLOTS = range(1, 9)


def _reagent_list(raw: dict) -> list[tuple[int, int]]:
    return [(raw[f'Reagent_{k}'], raw.get(f'ReagentCount_{k}', 0)) for k in _REAGENT_SLOTS if raw.get(f'Reagent_{k}')]


def _with_reagents(raw: dict, reagents) -> dict:
    """`raw` with its Reagent_n / ReagentCount_n replaced by `reagents` ((item, count), ...), the rest cleared."""
    out = {k: v for k, v in raw.items() if not k.startswith(('Reagent_', 'ReagentCount_'))}
    for k in _REAGENT_SLOTS:
        out[f'Reagent_{k}'], out[f'ReagentCount_{k}'] = reagents[k - 1] if k <= len(reagents) else (0, 0)
    return out


def _squished(raw: dict) -> dict:
    """`raw` with every old enchanting material swapped for its survivor, counts kept (merged when two map to one)."""
    merged: dict[int, int] = {}
    for item, count in _reagent_list(raw):
        item = SURVIVOR.get(item, item)
        merged[item] = merged.get(item, 0) + count
    return _with_reagents(raw, tuple(merged.items()))


