def _with_extra(overrides: dict) -> dict:
    """`overrides` with _HEROIC_EXTRA merged into the entries that are present."""
    merged = {}
    for entry, values in overrides.items():
        extra = _HEROIC_EXTRA.get(entry)
        if extra is not None:
            values = {**values, **{k: v for k, v in extra.items() if k != "columns"},
                      **({"columns": {**values.get("columns", {}), **extra["columns"]}} if "columns" in extra else {})}
        merged[entry] = values
    return merged


