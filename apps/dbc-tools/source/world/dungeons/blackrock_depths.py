# A heroic boss drops its own loot: `lootid` = its own heroic entry, whose groups source/items/blackrock_depths_loot.py
# declares (L-1 / L-2, copying the normal groups and adding the Heroic tiers). Off until they have: a lootid with no
# loot_template rows behind it drops nothing (Scholomance R-A S-2). L-1 flipped it with the wave 1 declarations (the
# wave 2 bosses' overrides are in `_wave("2", ...)`, applied once BIND_WAVE_2 binds them, and need L-2's groups); the
# test follows the flag.
_HEROIC_BOSS_OWN_LOOT = True


def _boss(health: int, heroic_entry: int | None = None, immunity: dict | None = None, **columns) -> dict:
    """A heroic boss: stun immune (1972, or `immunity`) and its own heroic loot (heroic_ids.lock). `columns` override
    any of the values."""
    values = dict(immunity or _STUN_IMMUNE)
    if heroic_entry is not None and _HEROIC_BOSS_OWN_LOOT:
        values["lootid"] = heroic_entry
    values.update(columns)
    return dict(health=health, columns=values)


# The wave switch of source/npcs/blackrock_depths/_common.py (BIND_WAVE_2), read from its text (the dungeon files never
# import the npc packages): a boss of sections 3 and 4 keeps its stock heroic copy until wave 2 binds it. Wave 1 is
# always bound. A missing file reads as off.
_WAVE_SWITCH = re.compile(r"^BIND_WAVE_(2)\s*=\s*(True|False)\s*$", re.MULTILINE)


def _bound_waves() -> set[str]:
    path = _KIT_NPCS / "_common.py"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    return {"1"} | {wave for wave, value in _WAVE_SWITCH.findall(text) if value == "True"}


_bound = _bound_waves()


def _wave(wave: str, overrides: dict) -> dict:
    """`overrides` once `wave` is bound, else nothing."""
    return overrides if wave in _bound else {}


