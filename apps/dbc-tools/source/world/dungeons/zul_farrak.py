_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "zul_farrak"
# `creature_template(<entry>, ...)` or a private helper taking the entry first (`_unit(301015, ...)`); the entry is a
# literal or a module-level constant of that file (`BERSERKER = 301015`). Never docstrings and comments.
_CREATURE_TEMPLATE_CALL = re.compile(r"\b(?:creature_template|_\w+)\(\s*(\d{6}|[A-Z][A-Z0-9_]*)\s*,")
_ENTRY_CONSTANT = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*(\d{6})\s*$", re.MULTILINE)
_DOCSTRING = re.compile(r'"""(?:.|\n)*?"""|\'\'\'(?:.|\n)*?\'\'\'')


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/zul_farrak/*.py declares with creature_template(<entry>, ...) or a private
    helper taking the entry first; the entry is a literal or a module-level constant of that file."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        text = _DOCSTRING.sub("", path.read_text(encoding="utf-8"))
        text = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
        constants = {name: int(value) for name, value in _ENTRY_CONSTANT.findall(text)}
        for arg in _CREATURE_TEMPLATE_CALL.findall(text):
            if arg.isdigit():
                found.add(int(arg))
            elif arg in constants:
                found.add(constants[arg])
    # Private spell helpers take a 6-digit id first too: keep the dungeon's own creature slice (ids.yaml).
    return found & set(range(301005, 301100))


