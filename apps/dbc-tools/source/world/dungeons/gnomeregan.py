def _own_loot(entry: int) -> dict:
    """The `lootid` column of a heroic boss with its own loot (only once `_HEROIC_BOSS_OWN_LOOT` is on)."""
    return {"lootid": _HEROIC_ID[entry]} if _HEROIC_BOSS_OWN_LOOT and entry in _HEROIC_LOOTID else {}


def _boss(entry: int, health: int, **more) -> dict:
    """A heroic boss: its health, the stun immunity set, the normal rows' flags and detection range, (with
    `_HEROIC_BOSS_OWN_LOOT`) its own heroic loot, and `more` override keys (`melee=`)."""
    return dict(health=health, columns={**_BOSS_COLUMNS, **_own_loot(entry)}, **more)


