_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "shadowfang_keep"
_CREATURE_TEMPLATE_CALL = re.compile(r"\bcreature_template\(\s*(\d+)\s*,")


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/shadowfang_keep/*.py declares with creature_template(<entry>, ...)."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        found.update(int(m) for m in _CREATURE_TEMPLATE_CALL.findall(path.read_text(encoding="utf-8")))
    return found


_declared = _declared_kit_entries()


def _boss(health: int, heroic_entry: int) -> dict:
    """A heroic boss drops its own loot: `lootid` = its own heroic entry (heroic_ids.lock), whose groups hold the
    Heroic tiers (source/items/shadowfang_keep_loot.py, WP-L)."""
    return dict(health=health, columns={**_STUN_IMMUNE, "lootid": heroic_entry})


