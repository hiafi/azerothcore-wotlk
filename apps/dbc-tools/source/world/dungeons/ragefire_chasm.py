# The reworked bosses' stun immunity set (source/npcs/ragefire_chasm/_common.py IMMUNITY_BOSS_STUN): -229 + STUN, no
# silence. The heroic copy reads the live normal row, so the columns are stated here rather than trusted to the
# declared edit. The same three values as `boss_columns()` of _common.py (the test pins them together).
_BOSS_COLUMNS = {
    "CreatureImmunitiesId": 1972,
    # INSTANCE_BIND | DONT_CALL_ASSISTANCE | IGNORE_ALL_ASSISTANCE_CALLS (section 7 #12 A): the trash beside a boss is
    # neither pulled by him nor pulls him, on heroic too (the flag stops only his first call; the AI's
    # SetAssistanceTimer(0) stops the rest: source/npcs/ragefire_chasm/_common.py)
    "flags_extra": 0x00000001 | 0x02000000 | 0x04000000,
    "detection_range": 12.0,
}

# A heroic boss drops its own loot: `lootid` = its own heroic entry, whose groups source/items/ragefire_chasm_loot.py
# declares (L-1). A lootid with no loot_template rows drops nothing, and generate.py --check stops on one, so the flag
# and that file go together; the test follows it. The ids are the mint order of heroic_ids.lock (the docstring).
_HEROIC_BOSS_OWN_LOOT = True
_HEROIC_LOOTID = {11517: 310496, 11518: 310497, 11519: 310498, 11520: 310499}


# Bazzalan's heroic swing at 2.0 s (STAGE-D3 Q2 A, provisional until the user rules): half the tier's 2,500. His
# heroic Sinister Strike is one of his own swings (weapon damage + 1) every 2 s, so a swing and a strike together make
# the tier's 2,500 per 2.0 s.
_BAZZALAN_MELEE = 1_250


def _boss(entry: int, health: int, **more) -> dict:
    """A heroic boss: its health, the stun immunity set, the normal rows' flags and detection range, (with
    `_HEROIC_BOSS_OWN_LOOT`) its own heroic loot, and `more` override keys (`melee=`)."""
    columns = dict(_BOSS_COLUMNS)
    if _HEROIC_BOSS_OWN_LOOT:
        columns["lootid"] = _HEROIC_LOOTID[entry]
    return dict(health=health, columns=columns, **more)


# The boss kit's units that fight on heroic and get a heroic template (handoff 3.3 / 3.6). Applied once a source file
# declares the unit with `creature_template(<entry>, ...)` (a heroic override needs a template this run declares), so
# there is nothing to edit when the WP lands. The Blood Globule's own `creature_template()` row names its heroic entry
# (310500, the docstring). Not listed on purpose (they run on their normal entry): the Borer 300985, the Soul Wisp
# 300986, the stalker 300988 and the entrance orc 300989.
_KIT_ADD_HEROIC = {
    300987: dict(health=6_000),  # Blood Globule (Starving: 24,000 across four, 6,000 each)
}

_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "ragefire_chasm"
# `creature_template(<entry>, ...)` or a private helper taking the entry first (`_unit(300987, ...)`); the entry is a
# literal or a module-level constant of that file (`BLOOD_GLOBULE = 300987`). Never docstrings and comments.
_CREATURE_TEMPLATE_CALL = re.compile(r"\b(?:creature_template|_\w+)\(\s*(\d{6}|[A-Z][A-Z0-9_]*)\s*,")
_ENTRY_CONSTANT = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*(\d{6})\s*$", re.MULTILINE)
_DOCSTRING = re.compile(r'"""(?:.|\n)*?"""|\'\'\'(?:.|\n)*?\'\'\'')


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/ragefire_chasm/*.py declares with creature_template(<entry>, ...) or a private
    helper taking the entry first; the entry is a literal or a module-level constant of that file."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        text = _DOCSTRING.sub("", path.read_text(encoding="utf-8"))
        text = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
        constants = {name: int(value) for name, value in _ENTRY_CONSTANT.findall(text)}
        for arg in _CREATURE_TEMPLATE_CALL.findall(text):
            if arg.isdigit():
                found.add(int(arg))
            elif arg in constants:
                found.add(constants[arg])
    # Private spell helpers take a 6-digit id first too: keep the dungeon's own creature slice (ids.yaml).
    return found & set(range(300985, 301000))


