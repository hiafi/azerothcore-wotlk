_STUN_IMMUNE = {"CreatureImmunitiesId": 1972}

# A heroic boss drops its own loot: `lootid` = its own heroic entry, whose groups source/items/
# scarlet_monastery_loot.py declares (L-1 / L-2, `boss_loot(tier=)`). On since L-1 declared the wave 1 heroic groups;
# a lootid with no loot_template rows behind it drops nothing (Scholomance R-A S-2), and generate.py --check stops on
# one (the wave 2 bosses' groups are L-2's). The test follows the flag.
_HEROIC_BOSS_OWN_LOOT = True


def _boss(health: int, heroic_entry: int | None = None, immunity: dict | None = None, **columns) -> dict:
    """A heroic boss: stun immune (1972, or `immunity`) and its own heroic loot (heroic_ids.lock). `columns` override
    any of the values."""
    values = dict(immunity or _STUN_IMMUNE)
    if heroic_entry is not None and _HEROIC_BOSS_OWN_LOOT:
        values["lootid"] = heroic_entry
    values.update(columns)
    return dict(health=health, columns=values)


