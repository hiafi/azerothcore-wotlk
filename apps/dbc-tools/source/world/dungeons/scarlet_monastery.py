# The boss kit's units (source/npcs/scarlet_monastery/): which entries a source file declares with
# `creature_template(<entry>, ...)`, or through a helper of its own that wraps it (`_part(300900, ...)`: a private
# function whose first argument is the entry). Never the docstrings and comments of the stubs, which name entries too.
_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "scarlet_monastery"
_CREATURE_TEMPLATE_CALL = re.compile(r"\b(?:creature_template|_\w+)\(\s*(\d{6}|[A-Z][A-Z0-9_]*)\s*,")
_ENTRY_CONSTANT = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*(\d{6})\s*$", re.MULTILINE)
_DOCSTRING = re.compile(r'"""(?:.|\n)*?"""|\'\'\'(?:.|\n)*?\'\'\'')


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/scarlet_monastery/*.py declares with creature_template(<entry>, ...) or a
    private helper taking the entry first; the entry is a literal or a module-level constant of that file
    (`GALVAR = 300903` ... `_risen(GALVAR, ...)`, R-1-KIT M-4)."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        text = _DOCSTRING.sub("", path.read_text(encoding="utf-8"))
        text = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
        constants = {name: int(value) for name, value in _ENTRY_CONSTANT.findall(text)}
        for arg in _CREATURE_TEMPLATE_CALL.findall(text):
            if arg.isdigit():
                found.add(int(arg))
            elif arg in constants:
                found.add(constants[arg])
    return found


_declared = _declared_kit_entries()


def _credit(entry: int):
    """The kill credit of a new boss creature, once a source file declares its template (generate.py stops on a credit
    creature that has none); None until then (the encounter is listed, no kill completes it)."""
    return credit_creature(entry) if entry in _declared else None


