# What an override states beyond its health and immunity set (kept apart from the per-unit lines below: other tests
# read those lines as text). `columns` merge into the override's `columns`, the other keys set the override's:
#  - INSTANCE_BIND (flags_extra 1) rides only on a unit that carries an encounter credit of its own (handoff 3.2 item 2,
#    the BRD rule): the council's pair (the instance credits by spell once both are dead), Mograine (the Last Stand
#    credits by spell, his real death in Whitemane's fight gives none: _common.py NO_INSTANCE_BIND) and the vigil
#    Fairbanks (no encounter of his own) state flags_extra 0 (a boss role would OR the bit in).
_NO_BIND = {"flags_extra": 0}
_HEROIC_EXTRA = {
    6488: dict(columns=_NO_BIND),  # the Fallen Champion
    6490: dict(columns=_NO_BIND),  # Azshir the Sleepless
    3976: dict(columns=_NO_BIND),  # Scarlet Commander Mograine (the Last Stand)
    300956: dict(columns=_NO_BIND),  # Fairbanks at the vigil (the Truth)
}


def _with_extra(overrides: dict) -> dict:
    """`overrides` with _HEROIC_EXTRA merged into the entries that are present."""
    merged = {}
    for entry, values in overrides.items():
        extra = _HEROIC_EXTRA.get(entry)
        if extra is not None:
            values = {**values, **{k: v for k, v in extra.items() if k != "columns"},
                      **({"columns": {**values.get("columns", {}), **extra["columns"]}} if "columns" in extra else {})}
        merged[entry] = values
    return merged


