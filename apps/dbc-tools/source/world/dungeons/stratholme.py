_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "stratholme"
_CREATURE_TEMPLATE_CALL = re.compile(r"\bcreature_template\(\s*(\d+)\s*,")


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/stratholme/*.py declares with creature_template(<entry>, ...)."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        found.update(int(m) for m in _CREATURE_TEMPLATE_CALL.findall(path.read_text(encoding="utf-8")))
    return found


_declared = _declared_kit_entries()


# A heroic boss drops its own loot: `lootid` = its own heroic entry, whose groups source/items/stratholme_loot.py
# declares (L-1, copying the normal groups and adding the Heroic tiers). It was off until L-1 declared them (Scholomance
# R-A S-2): a lootid with no loot_template rows behind it drops nothing. A Main Gate boss (wave 2) takes this switch
# too, but its entry is only an override while BIND_WAVE_2 is off, so its loot arrives with L-2.
_HEROIC_BOSS_OWN_LOOT = True


def _boss(health: int, heroic_entry: int | None = None, **columns) -> dict:
    """A heroic boss: stun immune (1972) and its own heroic loot (heroic_ids.lock). `columns` override any of the
    values (the Baron's -419)."""
    values = dict(_STUN_IMMUNE)
    if heroic_entry is not None and _HEROIC_BOSS_OWN_LOOT:
        values["lootid"] = heroic_entry
    values.update(columns)
    return dict(health=health, columns=values)


# The wave switch of source/npcs/stratholme/_common.py (BIND_WAVE_2), read from its text (the dungeon files never
# import the npc packages): a Main Gate boss keeps its stock heroic copy until wave 2 binds it. Wave 1 is always bound.
_WAVE_SWITCH = re.compile(r"^BIND_WAVE_(2)\s*=\s*(True|False)\s*$", re.MULTILINE)


def _bound_waves() -> set[str]:
    path = _KIT_NPCS / "_common.py"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    return {"1"} | {wave for wave, value in _WAVE_SWITCH.findall(text) if value == "True"}


_bound = _bound_waves()


def _wave(wave: str, overrides: dict) -> dict:
    """`overrides` once `wave` is bound, else nothing."""
    return overrides if wave in _bound else {}


