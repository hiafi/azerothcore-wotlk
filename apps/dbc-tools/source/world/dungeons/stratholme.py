"""
Stratholme (map 329): every creature of the dungeon as a reference declaration (dungeon difficulties E2, WP-G) and
its heroic (Stratholme build, WP-H). The `CREATURES` block is generated by apps/dbc-tools/extract_dungeon_creatures.py
from the live world DB; rerun it to refresh the block and never edit inside the markers. Hand edits go in the
`dungeon(...)` call: `extra=` (creatures the extraction cannot see, e.g. C++ summons and the boss kit's adds),
`roles=` (role corrections), `skip=` (entries that never get a heroic template) and `heroic=heroic(...)`.

The heroic follows the Deadmines (deadmines.py), Shadowfang Keep (shadowfang_keep.py) and Scholomance
(scholomance.py): MapDifficulty 1003, dungeon_access_template 125 and DungeonEncounter 1028-1040 are the next ids of
their blocks after Scholomance's (source/ids.yaml), a level 60 heroic template for each hostile creature
(lib/heroic_templates.py: the vanilla tier table and the overrides below) and every non-event spawn on heroic. The
heroic creature ids live in source/world/heroic_ids.lock, minted by a scoped write run (`generate.py --scope
stratholme`, lines from 310120); never move any of them once shipped.

The whole of map 329 goes heroic in wave 1 (handoff 2.5, 7.1 #5), but only the Service Entrance bosses (Barthilas,
the three ziggurat bosses, Ramstein, the Baron) are reworked in wave 1: the Main Gate bosses and their kit keep their
stock heroic copy until wave 2 binds them (`_wave("2", ...)`, the switch BIND_WAVE_2 of source/npcs/stratholme/
_common.py), like Scholomance's later waves.

Heroic health is the build spec's (docs/dungeons/stratholme-rework.md; handoff 3.6): group DPS x uptime x the kill
time. The doc names no heroic melee, so every creature takes the tier's (2,500 per 2.0 s swing for a boss); the tuning
stage (WP-T) changes the overrides below and nothing else. The reworked bosses take the stun immunity set 1972 (-229 +
STUN, the Deadmines', handoff 7.1 #3) on heroic like their normal rows; the Baron keeps his stock -419 (stun immune,
interrupt and silence immune). Grand Crusader Dathrohan (10812, the first form of Balnazzar's fight: an encounter's
boss with no encounter row of his own) is a boss by role, so he takes the boss tier's melee and INSTANCE_BIND like
Balnazzar; it carries no loot (Balnazzar's kill drops it).

Hard mode (the Baron's Ultimatum, Balnazzar's Grand Lie) is heroic only and is not a map difficulty: it needs no row
here. Its units (Ysida, Risen 300589; the moving swarm 300609 and the relic stalkers) exist only on heroic, are
declared by their own WPs (S15, S8) and get no heroic template: they spawn at their own entry (wave C mint rule).
Ysida Harmon (16031) is a friendly NPC (role npc) and gets none either.

The boss kit's combat adds (source/npcs/stratholme/, built by the boss WPs; ids 300580-300619, handoff 3.3) are
invisible to the extraction, so `extra=` lists them. A heroic override needs a creature_template this run declares,
and the adds do not exist until their WP lands, so `_KIT_ADD_HEROIC` is applied only to the adds whose
`creature_template(<id>, ...)` source/npcs/stratholme/ declares (`_declared_kit_entries`): nothing to edit when an add
lands. The stock-id kit adds (10387, 10876, 11030, 11054, 11197) and the Black Guard Sentry 10394 always exist.

SmartAI widening: the generator widens the normal-only SmartAI rows of the map's scripts to heroic by itself (the
`UPDATE smart_scripts SET event_flags = event_flags | 4` block of the scoped write run); on map 329 that is the
Rockwing Screecher 10409 (4 rows) and the Eye of Naxxramas 10411 (2 rows and a link row). No hand-written SQL rev.
"""

