_KIT_NPCS = Path(__file__).resolve().parents[2] / "npcs" / "scholomance"
_CREATURE_TEMPLATE_CALL = re.compile(r"\bcreature_template\(\s*(\d+)\s*,")


def _declared_kit_entries() -> set[int]:
    """The creature entries source/npcs/scholomance/*.py declares with creature_template(<entry>, ...)."""
    found: set[int] = set()
    for path in sorted(_KIT_NPCS.glob("*.py")):
        found.update(int(m) for m in _CREATURE_TEMPLATE_CALL.findall(path.read_text(encoding="utf-8")))
    return found


_declared = _declared_kit_entries()


# R-A S-2 / WP-L: a heroic boss drops its own loot: `lootid` = its own heroic entry, whose groups source/items/
# scholomance_loot.py declares (copying group 0 from the normal lootid; Marduk's holds only that copy).
_HEROIC_BOSS_OWN_LOOT = True


def _boss(health: int, heroic_entry: int | None = None, **columns) -> dict:
    """A heroic boss drops its own loot: `lootid` = its own heroic entry (heroic_ids.lock), whose groups hold the
    Heroic tiers (source/items/scholomance_loot.py). `columns` override any of the values."""
    values = dict(_STUN_IMMUNE)
    if heroic_entry is not None and _HEROIC_BOSS_OWN_LOOT:
        values["lootid"] = heroic_entry
    values.update(columns)
    return dict(health=health, columns=values)


# The wave switches of source/npcs/scholomance/_common.py (BIND_WAVE_B, BIND_WAVE_C; R-A S-11), read from its text
# (the dungeon files never import the npc packages): a later wave's boss keeps its stock heroic copy until its wave
# binds it.
_WAVE_SWITCH = re.compile(r"^BIND_WAVE_([BC])\s*=\s*(True|False)\s*$", re.MULTILINE)


def _bound_waves() -> set[str]:
    path = _KIT_NPCS / "_common.py"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    return {"A"} | {wave for wave, value in _WAVE_SWITCH.findall(text) if value == "True"}


_bound = _bound_waves()


def _wave(wave: str, overrides: dict) -> dict:
    """`overrides` once `wave` is bound, else nothing."""
    return overrides if wave in _bound else {}


