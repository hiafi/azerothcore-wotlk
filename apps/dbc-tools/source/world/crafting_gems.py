_META_EFFECTS = {
    "kaleidoscope": [KALEIDOSCOPE], "purist": [PURIST_A, PURIST_B], "relentless": [RELENTLESS],
    "bulwark": [BULWARK], "wellspring": [WELLSPRING],
}

# --- Gems: enchant + GemProperties + cut ------------------------------------------------------------------------------
_META_TEXT = {key: text for key, _name, _display, text, _extra in T.METAS}

for _gem in T.gems():
    if _gem["kind"] == "meta":
        _effects = [spell_effect(EnchantType.EQUIP_SPELL, s) for s in _META_EFFECTS[_gem["meta_key"]]]
        _text = _META_TEXT[_gem["meta_key"]]
    else:
        _effects = [stat_effect(stat, amount) for stat, amount in _gem["stats"]]
        _text = T.enchant_text(_gem["stats"])
    _enchant = enchant(_gem["enchant"], _text, *_effects, src_item=_gem["item"], min_level=_gem["level_gate"])
    gem(_gem["gemprop"], _enchant, _gem["color"])
    _cut(_gem)

