_ICON_WELLSPRING = 3184  # Spell_Magic_ManaGain

# CombatRating bits (Unit.h CombatRating), for SPELL_AURA_MOD_RATING's misc mask.
CR_CRIT = (1 << 8) | (1 << 9) | (1 << 10)
CR_HASTE = (1 << 17) | (1 << 18) | (1 << 19)
CR_PROC_CHANCE = 1 << 11
CR_MASTERY = 1 << 20
CR_VERSATILITY = 1 << 21
CR_COOLDOWN_HASTE = 1 << 22

# spell_proc (SpellMgr.h)
