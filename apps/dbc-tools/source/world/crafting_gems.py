_PROC_TAKEN_ANY_HIT = 0x00000008 | 0x00000020 | 0x00000080 | 0x00000200 | 0x00002000 | 0x00020000
_PROC_DONE_POSITIVE_SPELL = 0x00000400 | 0x00004000
_PROC_SPELL_PHASE_HIT = 0x2
_PROC_HIT_CRITICAL = 0x2

META_SPELLS = {
    "kaleidoscope": 207150, "kaleidoscope_buff_a": 207151, "kaleidoscope_buff_b": 207152,
    "purist_a": 207153, "purist_b": 207154, "relentless": 207155,
    "bulwark": 207156, "bulwark_shield": 207157, "wellspring": 207158, "wellspring_mana": 207159,
}


def _passive(key: str, name: str, effects: list, script: str, note: str):
    s = spell(
        id=META_SPELLS[key], name=name, school=School.NORMAL, attributes=_ATTR0_PASSIVE_HIDDEN, cast_time_ms=0,
        cooldown_ms=0, category_cooldown_ms=0, mana_cost=0, mana_cost_pct=0, range_yards=RANGE_SELF, duration_ms=0,
        effects=effects, spell_icon_id=1, notes=f'Crafting rework C5: {note}',
        raw_overrides={'SpellClassSet': 0, 'EquippedItemClass': -1, 'SpellLevel': 0, 'CastingTimeIndex': 1,
                       'Description_Lang_enUS': '', 'AuraDescription_Lang_enUS': '', **_TEXT_MASKS},
    )
    scripted_by(s, script)
    return s


def _aura(aura: int, misc: int = 0) -> Effect:
    return Effect(type=EffectType.APPLY_AURA, apply_aura=aura, misc_value=misc, implicit_target_a=_TARGET_UNIT_CASTER)


def _triggered(key: str, name: str, effects: list, duration_ms: int, icon: int, description: str,
               aura_description: str = ''):
    return spell(
        id=META_SPELLS[key], name=name, school=School.NORMAL, attributes=0, cast_time_ms=0, cooldown_ms=0,
        category_cooldown_ms=0, mana_cost=0, mana_cost_pct=0, range_yards=RANGE_SELF, duration_ms=duration_ms,
        effects=effects, spell_icon_id=icon,
        notes=f'Crafting rework C5: {name}, cast by the meta gem script with computed amounts.',
        raw_overrides={'SpellClassSet': 0, 'EquippedItemClass': -1, 'SpellLevel': 0, 'CastingTimeIndex': 1,
                       'Description_Lang_enUS': description, 'AuraDescription_Lang_enUS': aura_description,
                       **_TEXT_MASKS},
    )


