"""
Crafting rework C5: gems, meta gems and socket bonuses (`.agents/plans/crafting-rework/crafting-rework.C5-RESEARCH.md`,
rulings 2026-11-11).

Declares, from the table in `lib/crafting_gems_data.py`:

- the gem enchants (`SpellItemEnchantment` 5100-5194): a stat gem's stats, or a meta's equip spell(s). Rare, epic and
  meta enchants carry `MinLevel` 60, so `Player::ApplyEnchantment` leaves them inert below 60 and the Uncommon
  leveling gems are the pre-60 choice;
- `GemProperties` 2000-2094 (the socket color the client matches and the enchant the gem applies);
- the Jewelcrafting cuts (spells 207050-207144) and their `SkillLineAbility` rows (30920-31014). Rare, leveling and
  meta cuts are taught by the Jewelcrafting trainer list 113 (Silvermoon, Exodar, Stormwind, Orgrimmar); the epic cuts
  exist but nothing teaches them yet (recipes later, user 2026-11-11);
- the meta gem spells (207150-207159), scripted in `src/server/scripts/Custom/custom_crafting_gems.cpp`;
- +4 socket bonuses for the stats stock has none for (5600-5607; flat and unpriced like the stock ones, decision 2 A).

The gem items themselves (`item_template` + `items.csv`) are hand-written rows generated by `write_gem_items.py`.
"""

from lib.dsl import RANGE_SELF, AuraType, Effect, EffectType, School
from lib.dsl.enchants import enchant, gem, spell_effect, stat_effect, stat_enchant
from lib.dsl.registry import EnchantType, procs_on, scripted_by, skill_line_ability, spell, trained_by

from lib import crafting_gems_data as T

SKILL_JEWELCRAFTING = 755
JEWELCRAFTING_TRAINER = 113  # Kalinda, Aleinia, Farii, Theresa Denman, Lugrah

_TEXT_MASKS = {
    'Name_Lang_Mask': 16712190, 'NameSubtext_Lang_Mask': 16712190, 'NameSubtext_Lang_enUS': '',
    'Description_Lang_Mask': 16712190, 'AuraDescription_Lang_Mask': 16712190,
}
_TARGET_UNIT_CASTER = 1

# --- Cuts: stock row shape of the TBC cuts (Bold Living Ruby 31084) --------------------------------------------------
_ATTR0_IS_TRADESKILL_NOT_SHAPESHIFTED = 0x00010020
_ATTR1_NO_THREAT = 0x00000400
_EFFECT_CREATE_ITEM = 24
_INTERRUPT_FLAGS = 15
_CAST_INDEX_GEM_CUT = 35  # 12.5 s - 0.25 s/level, at least 5 s: the stock cuts' cast time
_SIMPLE_GRINDER = 20824  # Totem_1 of every stock cut
_SV_JEWELCRAFTING = 7373
_ICON_GEM_CUT = 1

# Trainer prices (copper), final (trainer 113 is not in the trainer cost discount allow-list).
_TRAIN_COST = {"leveling": 1000, "rare": 50000, "meta": 100000}


def _cut(gem: dict) -> None:
    kind = gem["kind"]
    spell(
        id=gem["cut"], name=gem["name"], school=School.NORMAL, attributes=_ATTR0_IS_TRADESKILL_NOT_SHAPESHIFTED,
        cast_time_ms=0, cooldown_ms=0, category_cooldown_ms=0, mana_cost=0, mana_cost_pct=0, range_yards=RANGE_SELF,
        duration_ms=0, effects=[Effect(type=_EFFECT_CREATE_ITEM, implicit_target_a=_TARGET_UNIT_CASTER)],
        spell_icon_id=_ICON_GEM_CUT,
        notes=f'Crafting rework C5: the Jewelcrafting cut of {gem["name"]} (item {gem["item"]}) from raw gem '
              f'{gem["raw"]}. Row shape copied from the stock cut Bold Living Ruby 31084.',
        raw_overrides={
            'SpellClassSet': 0, 'EquippedItemClass': -1, 'SpellLevel': 0, 'AttributesEx': _ATTR1_NO_THREAT,
            'CastingTimeIndex': _CAST_INDEX_GEM_CUT, 'InterruptFlags': _INTERRUPT_FLAGS, 'ProcChance': 101,
            'EffectItemType_1': gem["item"], 'Reagent_1': gem["raw"], 'ReagentCount_1': 1, 'Totem_1': _SIMPLE_GRINDER,
            'SpellVisualID_1': _SV_JEWELCRAFTING, 'Description_Lang_enUS': '', 'AuraDescription_Lang_enUS': '',
            **_TEXT_MASKS,
        },
    )
    skill_line_ability(id=gem["sla"], skill_line=SKILL_JEWELCRAFTING, spell_id=gem["cut"], min_skill_line_rank=1,
                       acquire_method=0,
                       raw_overrides={'TrivialSkillLineRankHigh': 1, 'TrivialSkillLineRankLow': 1})
    if kind in _TRAIN_COST:
        trained_by(gem["cut"], JEWELCRAFTING_TRAINER, req_level=0, money_cost=_TRAIN_COST[kind],
                   req_skill_line=SKILL_JEWELCRAFTING, req_skill_rank=1)


# --- Meta gem spells (207150-207159) ----------------------------------------------------------------------------------
_ATTR0_PASSIVE_HIDDEN = 0x000000C0  # PASSIVE | DO_NOT_DISPLAY, the stock meta equip spells' Attributes (39957)
STAT_STRENGTH, STAT_AGILITY, STAT_INTELLECT, STAT_SPIRIT = 0, 1, 3, 4
SCHOOL_MASK_ALL = 127
POWER_MANA = 0
