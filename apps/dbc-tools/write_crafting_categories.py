#!/usr/bin/env python3
"""
Crafting rework C7-UI: writes the trade skill category table for the client,
`client/ui-overrides/Interface/FrameXML/CraftingCategories.lua` (the private repo hiafi/wow-client-ui, shipped in
patch-X by `build_patch_x.py`). The hand-written `TradeSkillCategories.lua` next to it reads the table and shows:

- the crafted set recipes under one header per set, in level order (Wool first, Runecloth last, then the raid sets);
- the enchant item recipes (C6 basic enchants, tinkers and buckle, the C7 premium enchants and utility scrolls) under
  one header per slot ("Weapon", "Cloak", "Boots", ...), after the sets;
- the Missives under "Missives" (user 2026-11-12);
- the Alchemy potions and elixirs under Health Potions, Mana Potions, Battle Potions, Battle Elixirs, Guardian Elixirs
  and Utility Potions and Elixirs (`lib/crafting_alchemy_categories_data.py`, user 2026-11-13).

Table: `CRAFTING_CATEGORIES[recipe spell] = { header, order }`. The header is `crafting_sets_data.category_name()`; the
order sorts the sets by level, then inside a set the profession's own armor (by armor type, archetype and slot), the
armor pieces it makes for other armor types (Leatherworking waists, Blacksmithing wrists), then the other items. A
header takes the lowest order of its recipes, so the headers follow the sets. The slot headers come after (order
from 1001: the slot order below, then leveling, endgame, premium, utility, then the name), then Missives (2001),
then the Alchemy headers (3001, in their data order).

The file is deterministic (LF, sorted by spell id): a rerun with unchanged data writes nothing.
`lib/test_crafting_categories.py` checks the table.

    python3 write_crafting_categories.py [--check] [--out PATH]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

from lib import crafting_alchemy_categories_data as A  # noqa: E402
from lib import crafting_consumables_data as C  # noqa: E402
from lib import crafting_enchants_data as E  # noqa: E402
from lib import crafting_sets_data as T  # noqa: E402
from lib import crafting_utility_enchants_data as U  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
OUT_PATH = REPO_ROOT / "client" / "ui-overrides" / "Interface" / "FrameXML" / "CraftingCategories.lua"
ARMOR_ORDER = {"cloth": 0, "leather": 1, "mail": 2, "plate": 3}
FORBIDDEN = '|"\\'
# The slot headers of the enchant items in display order (the C6 slot words, "2H Weapon" spelled out, "Hands" as
# the Enchanting "Gloves"). Every profession's enchant items use them, not only Enchanting's.
SLOT_ORDER = ("Weapon", "Two-Hand Weapon", "Shield", "Off-Hand", "Ranged", "Head", "Shoulder", "Cloak", "Chest",
              "Bracer", "Gloves", "Waist", "Legs", "Boots", "Jewelry")
SLOT_HEADER = {"2H Weapon": "Two-Hand Weapon", "Hands": "Gloves"}
SLOT_ORDER_BASE, MISSIVE_ORDER_BASE, ALCHEMY_ORDER_BASE = 1001, 2001, 3001
MISSIVE_HEADER = "Missives"
# The Missive recipes (source/world/crafting_suffixes.py MISSIVES; the test reads them from there).
MISSIVE_RECIPES = tuple(range(207010, 207019))
TIER_ORDER = {"leveling": 0, "endgame": 1, "premium": 2, "utility": 3}

HEADER = (
    "-- Generated by apps/dbc-tools/write_crafting_categories.py from the lib/crafting_*_data.py tables. Do not\n"
    "-- edit.\n"
    "-- recipe spell id -> { trade skill header, sort order }: TradeSkillCategories.lua shows the crafted set recipes\n"
    "-- under one header per set, the enchant item recipes under one per slot and the Missives under their own\n"
    "-- (crafting rework C7-UI).\n"
)


def _sort_key(n: int, row: T.RecipeRow) -> tuple:
    item = row.item
    set_index = T.SETS.index(item.set)
    if item.armor is None:
        return set_index, 2, 0, n
    own = T.ARMOR_PROFESSION[item.armor] == item.profession
    return set_index, 0 if own else 1, ARMOR_ORDER[item.armor], n


def categories() -> dict[int, tuple[str, int]]:
    """Recipe spell -> (header, order), order 1.. over every set recipe."""
    rows = T.recipes()
    ranked = sorted(range(len(rows)), key=lambda n: _sort_key(n, rows[n]))
    out = {}
    for order, n in enumerate(ranked, start=1):
        row = rows[n]
        out[row.spell] = (T.category_name(row.item.profession, row.item.set.key), order)
    return out


def _slot_header(word: str) -> str:
    return SLOT_HEADER.get(word, word)


def enchant_recipes() -> list[tuple[int, str, str, str]]:
    """(recipe spell, slot header, tier, name) of every enchant item recipe."""
    words = {key: word for key, _p, _s, _st, _f, word, _t, _ph in E.SLOTS}
    out = [(row["craft_spell"], _slot_header(words[row["slot"]]), row["tier"], row["name"]) for row in E.enchants()]
    out += [(row["craft_spell"], _slot_header(words[row["slot"]]), "endgame", row["name"]) for row in E.tinkers()]
    out.append((E.BUCKLE["craft_spell"], "Waist", "endgame", E.BUCKLE["name"]))
    for p in C.PREMIUMS:
        slot = p.item_name.removeprefix("Scroll of Enchant ").split(" - ")[0]
        out.append((p.recipe_spell, _slot_header(slot), "premium", p.item_name))
    out += [(u.recipe, _slot_header(u.slot), "utility", u.name) for u in U.UTILITY]
    return out


def all_categories() -> dict[int, tuple[str, int]]:
    """The whole table: the set recipes, the enchant item recipes by slot, the Missives, the Alchemy headers."""
    out = categories()
    rows = sorted(enchant_recipes(), key=lambda r: (SLOT_ORDER.index(r[1]), TIER_ORDER[r[2]], r[3], r[0]))
    for order, (spell, header, _tier, _name) in enumerate(rows, start=SLOT_ORDER_BASE):
        out[spell] = (header, order)
    for order, spell in enumerate(MISSIVE_RECIPES, start=MISSIVE_ORDER_BASE):
        out[spell] = (MISSIVE_HEADER, order)
    alchemy = [(spell, header) for header, recipes in A.HEADERS.items() for spell, _name in recipes]
    for order, (spell, header) in enumerate(alchemy, start=ALCHEMY_ORDER_BASE):
        out[spell] = (header, order)
    return out


def render_lua(table: dict[int, tuple[str, int]]) -> str:
    lines = [HEADER + "CRAFTING_CATEGORIES = {"]
    for spell in sorted(table):
        name, order = table[spell]
        if any(ch in FORBIDDEN or not ch.isprintable() for ch in name):
            raise ValueError(f"category {name!r} of spell {spell}: not allowed in a Lua string")
        lines.append(f'    [{spell}] = {{ "{name}", {order} }},')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale, write nothing")
    parser.add_argument("--out", type=Path, default=OUT_PATH, help=f"output file (default: {OUT_PATH})")
    args = parser.parse_args()
    text = render_lua(all_categories())
    stale = not args.out.is_file() or args.out.read_bytes() != text.encode("utf-8")
    if args.check:
        if stale:
            print(f"stale: {args.out}")
        return 1 if stale else 0
    if stale:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_bytes(text.encode("utf-8"))
        print(f"wrote {args.out}")
    else:
        print(f"{args.out} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
