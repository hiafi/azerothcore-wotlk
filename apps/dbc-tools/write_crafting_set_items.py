#!/usr/bin/env python3
"""
Crafting rework C7: writes the crafted sets' hand-written rows from `lib/crafting_sets_data.py` (decisions 3d and 3e
of `.agents/plans/crafting-rework/crafting-rework.C7-RESEARCH.md`). The set items and their recipes are declared in
`source/items/crafting_sets.py` and `source/world/crafting_sets.py`.

- `data/sql/updates/pending_db_world/rev_crafting_c7_set_items.sql`: an `item_template` upsert for the raid recipe
  items (78000 + n; item_template rows are never deleted, codestyle-sql not_delete);
- the matching `source/items.csv` rows (Item.dbc), replacing any earlier rows in 78000-78999;
- `data/sql/updates/pending_db_world/rev_crafting_c7_set_loot.sql`: one reference pool per tier holding its recipe
  items, a roll of it on every boss of the tier (and Majordomo's cache), and the tier material on every boss and the
  tier's elite trash.

Run it after changing the data; `lib/test_crafting_sets.py` fails while the files and the data disagree.

    python3 write_crafting_set_items.py [--check]
"""

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

from lib import crafting_consumables_data as C  # noqa: E402
from lib import crafting_sets_data as T  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
ITEMS_SQL = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c7_set_items.sql"
LOOT_SQL = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c7_set_loot.sql"
ITEMS_CSV = TOOL_ROOT / "source" / "items.csv"
ITEM_RANGE = range(78000, 78800)  # 78800-78999: write_crafting_consumable_items.py
WIDTH = 120

COLUMNS = (
    "entry", "class", "subclass", "SoundOverrideSubclass", "name", "displayid", "Quality", "Flags", "BuyCount",
    "BuyPrice", "SellPrice", "InventoryType", "AllowableClass", "AllowableRace", "ItemLevel", "RequiredLevel",
    "RequiredSkill", "RequiredSkillRank", "maxcount", "stackable", "spellid_1", "spelltrigger_1", "spellcharges_1",
    "spellcooldown_1", "spellcategory_1", "spellcategorycooldown_1", "bonding", "description", "Material", "sheath",
    "VerifiedBuild",
)
CLASS_RECIPE = 9
QUALITY_EPIC = 4
ITEM_FLAG_PLAYERCAST = 0x40  # the stock recipes' Flags
BIND_ON_EQUIP = 2
SPELLTRIGGER_ON_USE = 0
CHARGES_CONSUMED = -1
SKILL_RANK = 300
SELL_PRICE = 50000
PREMIUM_TIER = "t1"

ITEMS_HEADER = """\
-- Crafting rework C7: the raid recipe items (hand-picked `item` block ids 78000-78999, Item.dbc rows in
-- apps/dbc-tools/source/items.csv). GENERATED by apps/dbc-tools/write_crafting_set_items.py from
-- lib/crafting_sets_data.py; edit the data and rerun, never this file. Each teaches the recipes of one armor type and
-- slot (or a group of backs, weapons or jewelry) of a raid tier's crafted set through its learn spell
-- (source/world/crafting_sets.py). Shaped like the stock Molten Core recipes (Plans: Fiery Chain Shoulders 17053):
-- class 9, the profession's subclass, skill 300; Epic, Bind on Equip (decision 3e). Upsert: item_template rows are
-- never deleted (codestyle-sql not_delete).
"""

LOOT_HEADER = """\
-- Crafting rework C7: the raid recipe and tier material drops
-- (.agents/plans/crafting-rework/crafting-rework.C7-RESEARCH.md decisions 3d and 3e). GENERATED by
-- apps/dbc-tools/write_crafting_set_items.py from lib/crafting_sets_data.py; edit the data and rerun, never this file.
-- Rates are first-pass data for the later scarcity stage.
"""


def _sql_value(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    return str(value)


def _wrap_tokens(tokens: list[str], first: str, last: str, indent: str = "    ") -> list[str]:
    """Join `tokens` with ", " after `first`, breaking only between tokens, so a string literal is never split."""
    lines, current = [], first
    for index, token in enumerate(tokens):
        piece = token + ("," if index < len(tokens) - 1 else last)
        joiner = "" if current.endswith("(") else " "
        if len(current) + len(joiner) + len(piece) > WIDTH:
            lines.append(current.rstrip())
            current = indent + piece
        else:
            current += joiner + piece
    lines.append(current)
    return lines


def item_rows() -> list[dict]:
    rows = []
    for recipe in T.raid_recipe_items():
        values = (recipe.entry, CLASS_RECIPE, T.RECIPE_SUBCLASS[recipe.profession], -1, recipe.name,
                  T.RECIPE_ITEM_DISPLAY, QUALITY_EPIC, ITEM_FLAG_PLAYERCAST, 1, 0, SELL_PRICE, 0, -1, -1,
                  T.RECIPE_ITEM_LEVEL, 0, recipe.profession, SKILL_RANK, 0, 1, recipe.learn_spell, SPELLTRIGGER_ON_USE,
                  CHARGES_CONSUMED, -1, 0, -1, BIND_ON_EQUIP, recipe.description, -1, 0, 0)
        rows.append(dict(zip(COLUMNS, values)))
    return rows


def render_items_sql(rows: list[dict]) -> str:
    out = [ITEMS_HEADER.rstrip("\n")]
    out += _wrap_tokens([f"`{c}`" for c in COLUMNS], "INSERT INTO `item_template` (", ") VALUES")
    for index, row in enumerate(rows):
        out += _wrap_tokens([_sql_value(row[c]) for c in COLUMNS], "(", ")" + ("," if index < len(rows) - 1 else ""))
    out += _wrap_tokens([f"`{c}` = VALUES(`{c}`)" for c in COLUMNS[1:]], "ON DUPLICATE KEY UPDATE", ";")
    return "\n".join(out) + "\n"


def csv_rows(rows: list[dict]) -> list[str]:
    return [f"{r['entry']},{CLASS_RECIPE},{r['subclass']},-1,-1,{r['displayid']},0,0,"
            f"{r['name']} (crafting rework C7 raid recipe)" for r in rows]


def render_csv(existing: str, rows: list[dict]) -> str:
    """`existing` with this writer's rows replaced, each new row before the first kept row with a higher id."""
    def row_id(line: str) -> int | None:
        head = line.split(",", 1)[0]
        return int(head) if head.isdigit() else None

    out = [line for line in existing.splitlines() if row_id(line) is None or row_id(line) not in ITEM_RANGE]
    for line in csv_rows(rows):
        entry = row_id(line)
        at = next((i for i, kept in enumerate(out) if (row_id(kept) or 0) > entry), len(out))
        out.insert(at, line)
    return "\n".join(out) + "\n"


def _ids(values) -> str:
    return ", ".join(str(v) for v in sorted(values))


def _delete_lines(prefix: str, values) -> list[str]:
    """`prefix` + `(ids);` as one-line statements of at most WIDTH characters, so the last one sits on the line just
    before the INSERT (codestyle-sql wants a DELETE there)."""
    out, chunk = [], []
    for value in sorted(values):
        if chunk and len(f"{prefix}({_ids(chunk + [value])});") > WIDTH:
            out.append(f"{prefix}({_ids(chunk)});")
            chunk = []
        chunk.append(value)
    out.append(f"{prefix}({_ids(chunk)});")
    return out


def _loot_values(rows: list[tuple]) -> list[str]:
    """(Entry, Item, Reference, Chance, GroupId, MinCount, MaxCount, Comment) tuples as VALUES lines."""
    out = []
    for index, (entry, item, ref, chance, group, low, high, comment) in enumerate(rows):
        end = ";" if index == len(rows) - 1 else ","
        out.append(f"({entry}, {item}, {ref}, {chance}, 0, 1, {group}, {low}, {high}, {_sql_value(comment)}){end}")
    return out


def _insert_lines(table: str) -> list[str]:
    return [f"INSERT INTO `{table}` (`Entry`, `Item`, `Reference`, `Chance`, `QuestRequired`, `LootMode`, `GroupId`,",
            "    `MinCount`, `MaxCount`, `Comment`) VALUES"]


def render_loot_sql() -> str:
    out = [LOOT_HEADER.rstrip("\n")]
    recipes_by_tier: dict[str, list] = {}
    for recipe in T.raid_recipe_items():
        recipes_by_tier.setdefault(recipe.set.key, []).append(recipe)
    for tier, pool in T.RECIPE_REFERENCE.items():
        recipes = recipes_by_tier[tier]
        bosses, chests = T.RAID_BOSSES[tier], T.RAID_CHESTS.get(tier, {})
        material = T.TIER_MATERIAL[tier]
        trash = [t for t in T.RAID_TRASH[tier] if t not in T.MATERIAL_STOCK_TRASH.get(tier, ())]
        label = T.RAID_WORD[tier]
        out.append("")
        out.append(f"-- {tier.upper()} ({label}): the recipe items, one per roll (group 1, equal chance).")
        pool_rows = [(pool, r.entry, 0, 0, 1, 1, 1, f"{label} raid recipe: {r.name}") for r in recipes]
        if tier == PREMIUM_TIER:  # the premium enchant recipes join the T1 pool (decision 4 A)
            pool_rows += [(pool, p.recipe_item, 0, 0, 1, 1, 1, f"{label} premium enchant recipe: {p.item_name}")
                          for p in C.PREMIUMS]
        out.append(f"DELETE FROM `reference_loot_template` WHERE `Entry` = {pool};")
        out += _insert_lines("reference_loot_template")
        out += _loot_values(pool_rows)
        out.append(f"-- Every {tier.upper()} boss rolls the pool at {T.RECIPE_CHANCE:g}% and drops the tier material "
                   f"at {T.MATERIAL_BOSS_CHANCE:g}% (1-{T.MATERIAL_BOSS_MAX}).")
        prefix = f"DELETE FROM `creature_loot_template` WHERE `Item` IN ({pool}, {material}) AND `Entry` IN "
        out += _delete_lines(prefix, bosses)
        out += _insert_lines("creature_loot_template")
        rows = []
        for entry, name in sorted(bosses.items()):
            rows.append((entry, pool, pool, T.RECIPE_CHANCE, 0, 1, 1, f"{name}: {label} raid recipes (crafting C7)"))
            rows.append((entry, material, 0, T.MATERIAL_BOSS_CHANCE, 0, 1, T.MATERIAL_BOSS_MAX,
                         f"{name}: {label} tier material (crafting C7)"))
        out += _loot_values(rows)
        if chests:
            out.append(f"DELETE FROM `gameobject_loot_template` WHERE `Item` IN ({_ids((pool, material))}) AND "
                       f"`Entry` IN ({_ids(chests)});")
            out += _insert_lines("gameobject_loot_template")
            rows = []
            for entry, name in sorted(chests.items()):
                rows.append((entry, pool, pool, T.RECIPE_CHANCE, 0, 1, 1, f"{name}: {label} raid recipes"))
                rows.append((entry, material, 0, T.MATERIAL_BOSS_CHANCE, 0, 1, T.MATERIAL_BOSS_MAX,
                             f"{name}: {label} tier material"))
            out += _loot_values(rows)
        out.append(f"-- The tier's elite trash drops the tier material at {T.MATERIAL_TRASH_CHANCE:g}% (trash with a "
                   "higher stock rate keeps it).")
        out += _delete_lines(f"DELETE FROM `creature_loot_template` WHERE `Item` = {material} AND `Entry` IN ", trash)
        out += _insert_lines("creature_loot_template")
        out += _loot_values([(entry, material, 0, T.MATERIAL_TRASH_CHANCE, 0, 1, 1,
                               f"{label} tier material, elite trash (crafting C7)") for entry in trash])
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the files are stale, write nothing")
    args = parser.parse_args()
    rows = item_rows()
    want = {ITEMS_SQL: render_items_sql(rows), ITEMS_CSV: render_csv(ITEMS_CSV.read_text(), rows),
            LOOT_SQL: render_loot_sql()}
    stale = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path}")
        return 1 if stale else 0
    for path, text in want.items():
        path.write_text(text)
    print(f"wrote {len(rows)} recipe items: " + ", ".join(str(p.relative_to(REPO_ROOT)) for p in want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
