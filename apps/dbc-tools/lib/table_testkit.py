"""
Shared fixtures for the Death Knight T1 tests (`test_spell_rune_cost.py`, `test_spell_threat.py`,
`test_creation_data.py`, `test_chr_class.py`, `test_override_sla.py`, `test_dk_t1_check.py`).
Not a test module itself: nothing here is collected.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path
from unittest import mock

TOOL_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = TOOL_ROOT.parents[1]
sys.path.insert(0, str(TOOL_ROOT))

from lib import spell_tables, sql_dump, trainer_state  # noqa: E402
from lib.dsl import registry  # noqa: E402

GENERATED_HEADER = "-- Generated by apps/dbc-tools/generate.py - DO NOT hand-edit.\n\n"


def load_dsl(source: str, ids_cfg: dict | None = None, live_data: dict | None = None, **kwargs) -> dict:
    """Run a class-file fixture and return its merged registry (`{merge_key: [rows]}`)."""
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "deathknight.py"
        path.write_text(source)
        reg = registry.load_class_file(path, ids_cfg=ids_cfg or {}, live_data=live_data, **kwargs)
    return {key: getattr(reg, key) for key in registry.MERGE_KEYS}


def spec_for(table: str) -> spell_tables.TableSpec:
    return next(spec for spec in spell_tables.SPELL_TABLES if spec.name == table)


def removal_for(table: str) -> spell_tables.RemovalSpec:
    return next(spec for spec in spell_tables.REMOVAL_TABLES if spec.table_name == table)


def index_for(table: str, live: list[dict], emitted: list[dict] | None = None, base: list[dict] | None = None):
    """A `SpellTableIndex` over one table, built the way `load_spell_table_index` builds the real one."""
    return spell_tables.SpellTableIndex(
        {table: live}, emitted={table: emitted or []}, base={table: base or []}, tables=(spec_for(table),),
    )


def render(table: str, index, declared: list[dict]) -> str:
    """The DELETE-then-INSERT block `render_blocks` would emit for the rows not already live."""
    from lib import sql_out  # noqa: PLC0415

    spec = spec_for(table)
    return sql_out.render_generic_table_block(
        table, spec.columns, spec.key_columns, index.rows_to_emit(spec, declared),
    )


def read_back(sql: str, table: str, columns: tuple[str, ...]) -> list[dict]:
    """The rows `sql` inserts, read the way the live-state reader (`trainer_state.load_table_rows`) reads a file."""
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "rev_1.sql"
        path.write_text(spell_tables.GENERATED_MARKER + "\n\n" + sql + "\n", encoding="utf-8")
        return sql_dump.read_table_rows(path, table, columns)


def codestyle_sql(text: str) -> subprocess.CompletedProcess:
    """Run the real `apps/codestyle/codestyle-sql.py` over `text` as a pending file. It ends with `git fetch` + `git
    diff` against origin/Playerbot; a no-op `git` first on PATH keeps it off the network (the per-file checks on the
    scratch pending file are what it is for)."""
    with tempfile.TemporaryDirectory() as d:
        pending = Path(d) / "data" / "sql" / "updates" / "pending_db_world"
        pending.mkdir(parents=True)
        (pending / "rev_1.sql").write_text(GENERATED_HEADER + text + "\n", encoding="utf-8")
        fake_bin = Path(d) / "bin"
        fake_bin.mkdir()
        (fake_bin / "git").write_text("#!/bin/sh\nexit 0\n")
        (fake_bin / "git").chmod(0o755)
        return subprocess.run(
            [sys.executable, str(REPO_ROOT / "apps" / "codestyle" / "codestyle-sql.py")],
            cwd=d, capture_output=True, text=True, env={**os.environ, "PATH": f"{fake_bin}:{os.environ['PATH']}"},
        )


def no_migrations():
    """Hermetic removal / prune tests: ignore the working tree's migrations (a generated rev may hold the DELETE)."""
    return mock.patch.object(trainer_state, "_migration_files_mentioning", return_value=[])


def generated_file(sql: str):
    """A context manager that makes `trainer_state._migration_files_mentioning` return one generated file of `sql`."""
    import contextlib  # noqa: PLC0415

    @contextlib.contextmanager
    def _ctx():
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "rev_1.sql"
            path.write_text(spell_tables.GENERATED_MARKER + "\n\n" + sql + "\n", encoding="utf-8")
            with mock.patch.object(trainer_state, "_migration_files_mentioning", return_value=[path]):
                yield path

    return _ctx()
