"""
The item tier label table for the client (item-variants plan v2 s6, stage IV4).

`render_lua(labels)` turns `ItemEmission.labels` (`{item_template entry: label}`, lib/item_emit.py) into the Lua source
of `client/ui-overrides/Interface/FrameXML/ItemTierLabels.lua`: one global table, `ITEM_TIER_LABELS`, that the
hand-written hook `ItemTierLabel.lua` (same folder) reads to print a green tier line under the item name on tooltips.
Heroic tiers are not in the table: the stock flag 0x8 already prints "Heroic". The file is deterministic (sorted by
entry, LF line endings) so a rerun with unchanged items writes nothing; `write()` returns whether it changed the file.
It ships in patch-X.mpq (`build_patch_x.py`).

Labels are written inside a Lua string that the client also scans for `|` escapes, so a label must be printable text
without `|`, a quote, a backslash or a line break; `render_lua` raises `ValueError` otherwise (generate.py turns that
into a run error before any file is written).
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
UI_OVERRIDES_DIR = REPO_ROOT / "client" / "ui-overrides"
OUT_PATH = UI_OVERRIDES_DIR / "Interface" / "FrameXML" / "ItemTierLabels.lua"

HEADER = (
    "-- Generated by apps/dbc-tools/generate.py (lib/item_labels.py) from the item variant ladders. Do not edit.\n"
    "-- item_template entry -> tier label shown in green under the item name by ItemTierLabel.lua. Heroic tiers are\n"
    "-- absent: the client prints its own \"Heroic\" line for the 0x8 item flag.\n"
)
FORBIDDEN = '|"\\'
_ENTRY_RE = re.compile(r'^\s*\[(\d+)\] = "([^"]*)",$')


def _check_label(entry: int, label: object) -> str:
    if not isinstance(entry, int) or isinstance(entry, bool) or entry <= 0:
        raise ValueError(f"item tier label: entry {entry!r} is not a positive item id")
    if not isinstance(label, str) or not label.strip() or label != label.strip():
        raise ValueError(f"item tier label for {entry}: {label!r} is empty or has leading/trailing space")
    for ch in label:
        if not ch.isprintable() or ch in FORBIDDEN:
            raise ValueError(f"item tier label for {entry}: {label!r} contains {ch!r}, not allowed in a tooltip label")
    return label


def render_lua(labels: dict[int, str]) -> str:
    """The Lua source of the label table, entries sorted; ValueError for an unusable entry or label."""
    lines = [HEADER + "ITEM_TIER_LABELS = {"]
    for entry in sorted(labels):
        lines.append(f'    [{entry}] = "{_check_label(entry, labels[entry])}",')
    lines.append("}")
    return "\n".join(lines) + "\n"


def read_table(path: Path = OUT_PATH) -> dict[int, str]:
    """The labels the current generated table holds (`{entry: label}`; empty when the file is missing). Used to keep
    a tier's label on its retire line (lib/item_ids.retire_suggestion)."""
    if not path.is_file():
        return {}
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = _ENTRY_RE.match(line)
        if m:
            out[int(m.group(1))] = m.group(2)
    return out


def is_stale(text: str, path: Path = OUT_PATH) -> bool:
    """True when `path` is missing or differs from `text` (the `--check` staleness note)."""
    return not path.is_file() or path.read_bytes() != text.encode("utf-8")


def write(text: str, path: Path = OUT_PATH) -> bool:
    """Write `text` to `path` unless it already holds exactly that; True when the file changed."""
    if not is_stale(text, path):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return True


def prepare(labels: dict[int, str]) -> tuple[str | None, list[str]]:
    """`(lua text, errors)` for generate.py: the text is None when a label is unusable (the error says which)."""
    try:
        return render_lua(labels), []
    except ValueError as exc:
        return None, [str(exc)]


def finish(text: str, check: bool = False, path: Path = OUT_PATH) -> str | None:
    """The run-summary note for the label table: `--check` reports a stale file without touching it, a write run
    writes it. None when the file is already current."""
    shown = path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path
    if check:
        return f"{shown} is stale: a full run rewrites it" if is_stale(text, path) else None
    return f"wrote {shown} (client tier labels; commit it, then build_patch_x.py)" if write(text, path) else None


def sync(labels: dict[int, str]) -> str | None:
    """Write the table for `labels` if it changed (a run that writes); the note to print, or None."""
    text, _errors = prepare(labels)  # generate.py already stopped the run on an unusable label
    return finish(text) if text is not None else None
