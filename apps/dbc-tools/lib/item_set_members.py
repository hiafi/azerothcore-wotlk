"""
The item set member table for the client (item variants, set tooltip fix, 2026-11-07).

`render_lua(members)` turns `SetExpansion.members` (lib/item_sets.py) into the Lua source of
`client/ui-overrides/Interface/FrameXML/ItemSetMembers.lua`: one global table, `ITEM_SET_MEMBERS`, that the hand-written
hook `ItemSetTooltip.lua` (same folder) reads. The client's ItemSet.dbc row holds at most 17 item ids, one per piece
(its first tier), so a Heroic or Empowered copy of a piece is not in the row and the client's own set tooltip counts
and colors it wrong, while the server counts by `item_template.itemset` (every tier). The table lists every tier of
every piece and each bonus's threshold and spell, so the hook can recount the worn pieces and color the bonus lines.

    ITEM_SET_MEMBERS = {
        [181] = {
            bonuses = { { 3, 200001 }, { 5, 200002 } },
            pieces = { { 70001, 70101, 70201 }, ... },   -- one list of item_template entries per piece, every tier
        },
    }

Deterministic (sets sorted by id, pieces and bonuses in declaration order, LF line endings), written only when it
changed (`item_labels.write`). Ships in patch-X.mpq (`build_patch_x.py`).
"""

from __future__ import annotations

from pathlib import Path

from . import item_labels

OUT_PATH = item_labels.UI_OVERRIDES_DIR / "Interface" / "FrameXML" / "ItemSetMembers.lua"
HEADER = (
    "-- Generated by apps/dbc-tools/generate.py (lib/item_set_members.py) from the item_set() declarations. Do not edit.\n"
    "-- set id -> bonuses { pieces worn, bonus spell id } and pieces (every tier's item_template entry of one piece),\n"
    "-- read by ItemSetTooltip.lua to recount the worn pieces: ItemSet.dbc lists only each piece's first tier.\n"
)


def _positive(what: str, value: object) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError(f"item set members: {what} {value!r} is not a positive integer")
    return value


def render_lua(members: dict[int, dict]) -> str:
    """The Lua source of the member table, sets sorted by id; ValueError for an unusable id."""
    lines = [HEADER + "ITEM_SET_MEMBERS = {"]
    for set_id in sorted(members):
        _positive("set id", set_id)
        decl = members[set_id]
        lines.append(f"    [{set_id}] = {{")
        bonuses = ", ".join(
            f"{{ {_positive('threshold', t)}, {_positive('bonus spell', s)} }}" for t, s in decl["bonuses"]
        )
        lines.append(f"        bonuses = {{ {bonuses} }},")
        lines.append("        pieces = {")
        for piece in decl["pieces"]:
            if not piece:
                raise ValueError(f"item set members: set {set_id} has a piece without a tier")
            ids = ", ".join(str(_positive("item entry", e)) for e in piece)
            lines.append(f"            {{ {ids} }},")
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def prepare(members: dict[int, dict]) -> tuple[str | None, list[str]]:
    """`(lua text, errors)` for generate.py."""
    try:
        return render_lua(members), []
    except ValueError as exc:
        return None, [str(exc)]


def finish(text: str, check: bool = False, path: Path = OUT_PATH) -> str | None:
    """The run-summary note: `--check` reports a stale file without touching it, a write run writes it."""
    shown = path.relative_to(item_labels.REPO_ROOT) if path.is_relative_to(item_labels.REPO_ROOT) else path
    if check:
        return f"{shown} is stale: a full run rewrites it" if item_labels.is_stale(text, path) else None
    if item_labels.write(text, path):
        return f"wrote {shown} (client set members; commit it, then build_patch_x.py)"
    return None


def sync(members: dict[int, dict]) -> str | None:
    """Write the table if it changed (a run that writes); the note to print, or None."""
    text, _errors = prepare(members)
    return finish(text) if text is not None else None
