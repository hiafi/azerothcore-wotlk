"""
`foreign` ids (source/ids.yaml, `lib/source.py`'s `foreign_ids`): an id inside a reserved block that another owner's SQL
holds. The one there is spell 200100, mod-transmog's Ethereal Warpweaver pet summon (the stock module inserts it from
`data/sql/db-world/2016_11_17_transmog_npc.sql` and its conf has `Transmogrification.PetSpellId = 200100`). Lasting
Flame rank 2 sat on it until 2026-11-06 and moved to 205100 (.agents/plans/dbc-replay-fix/spell-200100.REPORT.md).

Pinned here: the hole is in ids.yaml; the block DELETE is split around it, so a replay keeps the module's row; the
unchanged-block, stale-overlay and next-free-id code never treat it as ours; declaring it is an ERROR naming
mod-transmog; the mage now declares Lasting Flame rank 2 at 205100 inside its reservation; and the pending repair
migration restores the module's row byte for byte.

Run directly:

    apps/dbc-tools/.venv/bin/python3 apps/dbc-tools/lib/test_foreign_ids.py
"""

from __future__ import annotations

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = TOOL_ROOT.parents[1]
sys.path.insert(0, str(TOOL_ROOT))

import generate  # noqa: E402
from lib import dbcfmt, ids, resolve, source, sql_dump, sql_out, stale_overlay  # noqa: E402

IDS = source.load_ids(TOOL_ROOT / "source" / "ids.yaml")
SPELL_BLOCK = IDS["spell"]
TRANSMOG_SPELL = 200100
LASTING_FLAME_RANK_2 = 205100
TRANSMOG_SQL = REPO_ROOT / "modules" / "mod-transmog" / "data" / "sql" / "db-world" / "2016_11_17_transmog_npc.sql"
TRANSMOG_CONF = REPO_ROOT / "modules" / "mod-transmog" / "conf" / "transmog.conf.dist"
PENDING_DIR = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world"
# A small block with one hole, for the unit tests below (the real block is checked separately).
BLOCK = {"start": 200000, "end": 200199, "foreign": {200100: "mod-transmog (test)"}}
HEADER = "-- Generated by apps/dbc-tools/generate.py — DO NOT hand-edit."


def _spell(spell_id: int, name: str = "x") -> dict:
    return {"ID": spell_id, "Name_Lang_enUS": name}


def _emit(rows: list[dict], id_range: dict = BLOCK, edited_ids: list[int] | None = None) -> str:
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "rev_1.sql"
        sql_out.emit_pending_sql(out, [(dbcfmt.SPELL, id_range, rows, edited_ids or [])], HEADER)
        return out.read_text(encoding="utf-8")


class IdsYamlTest(unittest.TestCase):
    def test_spell_200100_is_the_one_foreign_id_and_names_mod_transmog(self):
        foreign = source.foreign_ids(SPELL_BLOCK)
        self.assertEqual(list(foreign), [TRANSMOG_SPELL])
        self.assertIn("mod-transmog", foreign[TRANSMOG_SPELL])
        self.assertEqual((SPELL_BLOCK["start"], SPELL_BLOCK["end"]), (200000, 209999))

    def test_no_other_block_has_foreign_ids(self):
        for name, cfg in IDS.items():
            if name not in ("spell", "reservations"):
                with self.subTest(block=name):
                    self.assertEqual(source.foreign_ids(cfg), {})

    def test_no_reservation_covers_a_foreign_id(self):
        for owner, tables in IDS["reservations"].items():
            cfg = tables.get("spell")
            if cfg:
                with self.subTest(owner=owner):
                    self.assertFalse(cfg["start"] <= TRANSMOG_SPELL <= cfg["end"])

    def test_lasting_flame_rank_2_sits_in_the_mage_spell_reservation(self):
        mage = IDS["reservations"]["mage"]["spell"]
        self.assertEqual(mage, {"start": 205100, "end": 205199})
        self.assertTrue(mage["start"] <= LASTING_FLAME_RANK_2 <= mage["end"])

    @unittest.skipUnless(TRANSMOG_SQL.is_file() and TRANSMOG_CONF.is_file(), "modules/mod-transmog is not checked out")
    def test_mod_transmog_still_owns_200100(self):
        """If the module ever moves its spell, the hole (and the pending repair) can go: this fails to say so."""
        self.assertIn("DELETE FROM `spell_dbc` WHERE `ID` = 200100;", TRANSMOG_SQL.read_text(encoding="utf-8"))
        self.assertIn("Transmogrification.PetSpellId = 200100", TRANSMOG_CONF.read_text(encoding="utf-8"))


class SourceHelpersTest(unittest.TestCase):
    def test_in_range_excludes_the_hole(self):
        self.assertTrue(source.in_range(200099, BLOCK))
        self.assertFalse(source.in_range(200100, BLOCK))
        self.assertTrue(source.in_range(200101, BLOCK))
        self.assertFalse(source.in_range(200200, BLOCK))

    def test_a_block_without_foreign_is_unchanged(self):
        plain = {"start": 1, "end": 3}
        self.assertEqual(source.foreign_ids(plain), {})
        self.assertTrue(source.in_range(2, plain))

    def test_a_declaration_on_the_hole_is_an_error_naming_the_owner(self):
        errors = source.foreign_id_errors([{"id": 200100, "name": "Lasting Flame"}, {"id": 200101}], SPELL_BLOCK)
        self.assertEqual(len(errors), 1)
        self.assertIn("spell 200100 (Lasting Flame)", errors[0])
        self.assertIn("mod-transmog", errors[0])

    def test_next_free_id_skips_the_hole(self):
        cfg = {"spell": {"start": 200099, "end": 200101, "foreign": {200100: "mod-transmog"}}}
        self.assertEqual(ids.next_free_id(cfg, "spell", {200099}), 200101)
        with self.assertRaises(ids.NoFreeIdError):
            ids.next_free_id(cfg, "spell", {200099, 200101})


class BlockSqlTest(unittest.TestCase):
    def test_block_ranges_split_around_the_hole(self):
        self.assertEqual(sql_out.block_ranges(BLOCK), [(200000, 200099), (200101, 200199)])
        self.assertEqual(sql_out.block_ranges(SPELL_BLOCK), [(200000, 200099), (200101, 209999)])
        self.assertEqual(sql_out.block_ranges({"start": 5, "end": 9}), [(5, 9)])
        self.assertEqual(sql_out.block_ranges({"start": 5, "end": 9, "foreign": {5: "a", 9: "b"}}), [(6, 8)])
        self.assertEqual(sql_out.block_ranges({"start": 5, "end": 5, "foreign": {5: "a"}}), [])

    def test_the_spell_block_delete_never_names_200100(self):
        text = _emit([_spell(200099), _spell(200101)], SPELL_BLOCK)
        self.assertIn("DELETE FROM `spell_dbc` WHERE `ID` BETWEEN 200000 AND 200099;", text)
        self.assertIn("DELETE FROM `spell_dbc` WHERE `ID` BETWEEN 200101 AND 209999;", text)
        self.assertNotIn("BETWEEN 200000 AND 209999", text)
        self.assertNotIn("(200100,", text)

    def test_a_row_or_edit_on_the_hole_is_refused(self):
        with self.assertRaisesRegex(ValueError, "mod-transmog"):
            _emit([_spell(200100)])
        with self.assertRaisesRegex(ValueError, "mod-transmog"):
            _emit([], edited_ids=[200100])

    def test_a_replay_of_the_block_keeps_the_module_row(self):
        rows = {200099: _spell(200099, "old"), 200100: _spell(200100, "Ethereal Warpweaver"), 200150: _spell(200150)}
        sql_dump.apply_statements(rows, dbcfmt.SPELL, _emit([_spell(200099, "new"), _spell(200101)]))
        self.assertEqual(sorted(rows), [200099, 200100, 200101])
        self.assertEqual(rows[200100]["Name_Lang_enUS"], "Ethereal Warpweaver")
        self.assertEqual(rows[200099]["Name_Lang_enUS"], "new")

    @unittest.skipUnless((REPO_ROOT / "apps" / "codestyle" / "codestyle-sql.py").is_file(), "linter not present")
    def test_the_split_block_passes_the_real_linter(self):
        import importlib.util
        path = REPO_ROOT / "apps" / "codestyle" / "codestyle-sql.py"
        spec = importlib.util.spec_from_file_location("codestyle_sql_under_test", path)
        linter = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(linter)
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "rev_1.sql"
            sql_out.emit_pending_sql(out, [(dbcfmt.SPELL, SPELL_BLOCK, [_spell(200099)], [116])], HEADER)
            with out.open(encoding="utf-8") as f:
                for check in (
                    linter.multiple_blank_lines_check, linter.trailing_whitespace_check, linter.sql_check,
                    linter.insert_delete_safety_check, linter.semicolon_check, linter.backtick_check,
                ):
                    check(f, str(out))
                    f.seek(0)
        self.assertFalse(linter.error_handler, linter.results)


class NotOursTest(unittest.TestCase):
    def test_unchanged_block_check_ignores_the_module_row(self):
        rows = [_spell(200099)]
        existing = {200099: _spell(200099), 200100: _spell(200100, "Ethereal Warpweaver")}
        self.assertFalse(resolve.reserved_range_changed(rows, "ID", BLOCK, [], existing))
        # without the hole the module row would read as a row to remove, so every run would re-emit the block
        self.assertTrue(resolve.reserved_range_changed(rows, "ID", {"start": 200000, "end": 200199}, [], existing))

    def test_resolve_rows_never_counts_the_hole_as_new_block_content(self):
        resolved = resolve.resolve_rows([{"id": 200100}], BLOCK, {200100: {"ID": 200100}}, lambda e: {"ID": e["id"]})
        self.assertEqual((resolved.entries, resolved.edited_ids, resolved.unchanged), ([], [], 1))

    def test_stale_overlay_skips_a_generated_row_on_the_hole(self):
        """Live today: the last generated rev wrote Lasting Flame at 200100. That row is not ours to judge."""
        overlay = stale_overlay.OverlayState()
        old_rev = _emit([_spell(200099), _spell(200100, "Lasting Flame")], {"start": 200000, "end": 200199})
        stale_overlay.apply_file(overlay, dbcfmt.SPELL, old_rev, True)
        self.assertEqual(overlay.generated, {200099, 200100})
        declared = {200099: overlay.rows[200099]}
        stale = stale_overlay.find_stale(BLOCK, declared, set(), overlay, {}, prune=True)
        self.assertFalse(stale.reserved_changed)
        self.assertEqual((stale.deletes, stale.kept_undeclared, stale.reemit), ([], [], []))

    def test_generate_block_ids_leave_the_hole_out(self):
        watched = generate._block_ids(SPELL_BLOCK, [116])
        self.assertNotIn(200100, watched)
        self.assertIn(116, watched)
        self.assertEqual(len(watched), 10000)  # 200000-209999 less 200100, plus 116

    def test_generate_prints_an_error_naming_mod_transmog(self):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            failed = generate._foreign_id_errors([{"id": 200100, "name": "Lasting Flame"}], IDS, "gcd haste: ")
        self.assertTrue(failed)
        self.assertRegex(out.getvalue(), r"^ERROR: gcd haste: spell 200100 \(Lasting Flame\) .*mod-transmog")
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertFalse(generate._foreign_id_errors([{"id": 205100}], IDS))


