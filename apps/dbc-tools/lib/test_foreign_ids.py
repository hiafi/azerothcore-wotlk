class PendingRepairTest(unittest.TestCase):
    """The hand-written pending migration that puts mod-transmog's row back over the Lasting Flame row the earlier
    generated revs left at 200100. It must sort after every pending rev that inserts 200100 (DBUpdater applies pending
    files by name), and carry the module's DELETE + INSERT unchanged."""

    @classmethod
    def setUpClass(cls):
        cls.repairs = [p for p in sorted(PENDING_DIR.glob("rev_*.sql"))
                       if "mod-transmog" in p.read_text(encoding="utf-8").split("\n", 1)[0]]

    def test_there_is_exactly_one_repair(self):
        self.assertEqual(len(self.repairs), 1, [p.name for p in self.repairs])

    def test_it_sorts_after_every_pending_rev_that_writes_200100(self):
        repair = self.repairs[0]
        writers = [p for p in sorted(PENDING_DIR.glob("rev_*.sql")) if p != repair
                   and "(200100," in p.read_text(encoding="utf-8")]
        self.assertTrue(all(p.name < repair.name for p in writers), [p.name for p in writers if p.name > repair.name])

    @unittest.skipUnless(TRANSMOG_SQL.is_file(), "modules/mod-transmog is not checked out")
    def test_it_carries_the_module_statements(self):
        """Verbatim but for the module's `) VALUE` keyword, written `) VALUES` (same statement in MySQL) because
        apps/codestyle/codestyle-sql.py's backtick check reads a bare `VALUE` as an unquoted column."""
        module = TRANSMOG_SQL.read_text(encoding="utf-8").splitlines()
        start = module.index("DELETE FROM `spell_dbc` WHERE `ID` = 200100;")
        expected = module[start:start + 3]
        self.assertTrue(expected[1].endswith(") VALUE"))
        expected[1] += "S"
        statements = [line for line in self.repairs[0].read_text(encoding="utf-8").splitlines()
                      if not line.startswith("--")]
        self.assertEqual(statements, expected)

    @unittest.skipUnless(TRANSMOG_SQL.is_file(), "modules/mod-transmog is not checked out")
    def test_replayed_it_leaves_the_module_row(self):
        rows = {200100: _spell(200100, "Lasting Flame")}
        sql_dump.apply_statements(rows, dbcfmt.SPELL, self.repairs[0].read_text(encoding="utf-8"))
        module_rows: dict[int, dict] = {}
        sql_dump.apply_statements(module_rows, dbcfmt.SPELL, TRANSMOG_SQL.read_text(encoding="utf-8"))
        self.assertEqual(rows[200100]["Name_Lang_enUS"], "Ethereal Warpweaver")
        self.assertEqual(rows, module_rows)


