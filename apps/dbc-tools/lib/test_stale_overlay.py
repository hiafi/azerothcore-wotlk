"""
Stale overlay rows (lib/stale_overlay.py): a row an earlier generate.py run wrote into a still-pending migration must be
removed when its declaration goes back to stock values or goes away. The Shockwave case: talent 1872 was moved from its
stock cell (10, 1) to (10, 0) in one run and back to (10, 1) in a later one; the later run saw "equals existing" (the
earlier file was still pending, so not part of `state.load_existing_rows`) and emitted nothing, leaving (10, 0) live in
`talent_dbc` until a hand-written DELETE (docs/bugs-and-fixes.md, 2026-10-30).

Run directly:

    apps/dbc-tools/.venv/bin/python3 -m pytest apps/dbc-tools/lib/test_stale_overlay.py -q
"""

from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lib import dbcfmt, sql_out, stale_overlay  # noqa: E402

TALENT = dbcfmt.TALENT
TALENT_RANGE = {"start": 60000, "end": 60799}
SHOCKWAVE = 1872
HEADER = "-- Generated by apps/dbc-tools/generate.py — DO NOT hand-edit."


def _talent(talent_id: int, tier: int, column: int, rank1: int = 46968) -> dict:
    row = {c: 0 for c in TALENT.columns}
    row.update(ID=talent_id, TabID=163, TierID=tier, ColumnIndex=column, SpellRank_1=rank1)
    return row


def _generated_sql(rows: list[dict], edited_ids: list[int]) -> str:
    """The text generate.py writes for a talent block (through the real renderer)."""
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "rev.sql"
        sql_out.emit_pending_sql(out, [(TALENT, TALENT_RANGE, rows, edited_ids)], HEADER)
        return out.read_text(encoding="utf-8")


STOCK_SHOCKWAVE = _talent(SHOCKWAVE, 10, 1)
MOVED_SHOCKWAVE = _talent(SHOCKWAVE, 10, 0)
CUSTOM = _talent(60006, 8, 2, rank1=204000)
STOCK = {SHOCKWAVE: STOCK_SHOCKWAVE}


def _overlay(*files: tuple[str, bool]) -> stale_overlay.OverlayState:
    state = stale_overlay.OverlayState()
    for text, generated in files:
        stale_overlay.apply_file(state, TALENT, text, generated)
    return state


def _find(overlay, declared_rows, emitted=(), prune=True):
    return stale_overlay.find_stale(
        TALENT_RANGE, {r["ID"]: r for r in declared_rows}, set(emitted), overlay, STOCK, prune=prune,
    )


class ShockwaveBackToStockTest(unittest.TestCase):
    def setUp(self):
        # Run 1 (pending, never promoted): Shockwave moved to (10, 0) as an edit of a stock row.
        self.s1 = (_generated_sql([CUSTOM, MOVED_SHOCKWAVE], [SHOCKWAVE]), True)

    def test_back_at_stock_deletes_the_live_row(self):
        stale = _find(_overlay(self.s1), [CUSTOM, STOCK_SHOCKWAVE])
        self.assertEqual(stale.deletes, [SHOCKWAVE])
        self.assertEqual(stale.undeclared, [])
        self.assertEqual(stale.reemit, [])
        self.assertFalse(stale.reserved_changed)

    def test_emitted_sql_deletes_without_insert_and_converges(self):
        overlay = _overlay(self.s1)
        stale = _find(overlay, [CUSTOM, STOCK_SHOCKWAVE])
        # Run 2's block: the reserved rows plus the delete-only id, as generate.py passes them.
        text = _generated_sql([CUSTOM], stale.deletes)
        self.assertIn(f"DELETE FROM `talent_dbc` WHERE `ID` IN ({SHOCKWAVE});", text)
        self.assertNotIn(f"({SHOCKWAVE}, ", text)
        stale_overlay.apply_file(overlay, TALENT, text, True)
        self.assertNotIn(SHOCKWAVE, overlay.rows)
        again = _find(overlay, [CUSTOM, STOCK_SHOCKWAVE])
        self.assertEqual((again.deletes, again.reemit, again.reserved_changed), ([], [], False))

    def test_delete_only_block_is_written(self):
        """A run whose only change is the stale delete still writes a file (no rows in any block)."""
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "rev.sql"
            self.assertTrue(sql_out.emit_pending_sql(out, [(TALENT, TALENT_RANGE, [], [SHOCKWAVE])], HEADER))
            self.assertIn(f"WHERE `ID` IN ({SHOCKWAVE});", out.read_text(encoding="utf-8"))

    def test_hand_written_delete_is_honoured(self):
        """The 2026-10-30 hand fix: once a DELETE has run, nothing more is emitted."""
        hand = ("DELETE FROM `talent_dbc` WHERE `ID` = 1872;\n", False)
        stale = _find(_overlay(self.s1, hand), [CUSTOM, STOCK_SHOCKWAVE])
        self.assertEqual(stale.deletes, [])

    def test_still_moved_is_not_stale(self):
        stale = _find(_overlay(self.s1), [CUSTOM, MOVED_SHOCKWAVE])
        self.assertEqual((stale.deletes, stale.reemit), ([], []))

    def test_already_emitted_edit_is_left_to_resolve(self):
        stale = _find(_overlay(self.s1), [CUSTOM, _talent(SHOCKWAVE, 9, 1)], emitted=[SHOCKWAVE])
        self.assertEqual((stale.deletes, stale.reemit, stale.drop), ([], [], []))

    def test_other_non_stock_value_is_reemitted(self):
        """Declared row differs from the live generated row but is not stock: an edit, not a delete."""
        stale = _find(_overlay(self.s1), [CUSTOM, _talent(SHOCKWAVE, 9, 1)])
        self.assertEqual((stale.deletes, stale.reemit), ([], [SHOCKWAVE]))

    def test_no_longer_declared_deletes(self):
        stale = _find(_overlay(self.s1), [CUSTOM])
        self.assertEqual(stale.deletes, [SHOCKWAVE])
        self.assertEqual(stale.undeclared, [SHOCKWAVE])

    def test_no_prune_keeps_undeclared_rows(self):
        """--no-prune: a no-longer-declared generated row is reported, not deleted; declared-at-stock still is."""
        stale = _find(_overlay(self.s1), [CUSTOM], prune=False)
        self.assertEqual((stale.deletes, stale.undeclared), ([], []))
        self.assertEqual(stale.kept_undeclared, [SHOCKWAVE])
        stale = _find(_overlay(self.s1), [CUSTOM, STOCK_SHOCKWAVE], prune=False)
        self.assertEqual(stale.deletes, [SHOCKWAVE])

    def test_undeclared_custom_row_without_stock_is_kept(self):
        orphan = _talent(5000, 1, 1)
        stale = _find(_overlay((_generated_sql([CUSTOM, orphan], [5000]), True)), [CUSTOM])
        self.assertEqual(stale.deletes, [])
        self.assertEqual(stale.kept_undeclared, [5000])

    def test_hand_written_row_is_not_ours(self):
        """A hand-written INSERT or UPDATE after the generated row takes it out of the generated set."""
        hand_update = ("UPDATE `talent_dbc` SET `ColumnIndex` = 2 WHERE `ID` = 1872;\n", False)
        self.assertEqual(_find(_overlay(self.s1, hand_update), [CUSTOM, STOCK_SHOCKWAVE]).deletes, [])
        hand_insert = (_generated_sql([MOVED_SHOCKWAVE], []).replace(HEADER, "-- hand fix"), False)
        self.assertEqual(_find(_overlay(self.s1, hand_insert), [CUSTOM, STOCK_SHOCKWAVE]).deletes, [])

    def test_stock_valued_edit_with_no_overlay_row_is_dropped(self):
        """After the hand-written DELETE, `load_existing_rows` reads 1872 as missing, so resolve marks the stock
        declaration as an edit; there is nothing to write."""
        hand = ("DELETE FROM `talent_dbc` WHERE `ID` = 1872;\n", False)
        stale = _find(_overlay(self.s1, hand), [CUSTOM, STOCK_SHOCKWAVE], emitted=[SHOCKWAVE])
        self.assertEqual((stale.drop, stale.deletes), ([SHOCKWAVE], []))

    def test_stock_valued_edit_over_generated_row_becomes_delete(self):
        stale = _find(_overlay(self.s1), [CUSTOM, STOCK_SHOCKWAVE], emitted=[SHOCKWAVE])
        self.assertEqual((stale.drop, stale.deletes), ([SHOCKWAVE], [SHOCKWAVE]))

    def test_base_dump_row_is_reemitted_not_deleted(self):
        """An id the base dump has: deleting would lose the dump row, so the declared row is written instead."""
        overlay = _overlay(self.s1)
        overlay.base_ids.add(SHOCKWAVE)
        stale = _find(overlay, [CUSTOM, STOCK_SHOCKWAVE])
        self.assertEqual((stale.deletes, stale.reemit), ([], [SHOCKWAVE]))

    def test_reserved_block_row_removed_while_pending(self):
        """A reserved-block row a pending run added and the declaration later dropped: the block must be re-emitted
        (its BETWEEN delete removes it), even though promoted state never had the row."""
        stale = _find(_overlay(self.s1), [STOCK_SHOCKWAVE])
        self.assertTrue(stale.reserved_changed)


if __name__ == "__main__":
    unittest.main()
