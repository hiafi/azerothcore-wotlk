#!/usr/bin/env python3
"""
Crafting rework C7: writes the hand-written item rows of the premium enchants, flasks, raid buff scrolls, boss runes and
the Darkmoon tarot from `lib/crafting_consumables_data.py` (their spells: `source/world/crafting_consumables.py`).

- `data/sql/updates/pending_db_world/rev_crafting_c7_consumable_items.sql`: an `item_template` upsert for every item
  (78800-78999; item_template rows are never deleted), and the tarot's loot (one random card of the four vanilla
  decks);
- the matching `source/items.csv` rows (Item.dbc), replacing any earlier rows in 78800-78999.

The premium enchant recipe items drop from the T1 raid recipe pool (`write_crafting_set_items.py` adds them).
Run it after changing the data; `lib/test_crafting_consumables.py` fails while the files and the data disagree.

    python3 write_crafting_consumable_items.py [--check]
"""

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

import write_crafting_set_items as S  # noqa: E402
from lib import crafting_consumables_data as T  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
SQL_PATH = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c7_consumable_items.sql"
ITEMS_CSV = TOOL_ROOT / "source" / "items.csv"
ITEM_RANGE = T.ITEM_RANGE

COLUMNS = (
    "entry", "class", "subclass", "SoundOverrideSubclass", "name", "displayid", "Quality", "Flags", "BuyCount",
    "BuyPrice", "SellPrice", "InventoryType", "AllowableClass", "AllowableRace", "ItemLevel", "RequiredLevel",
    "RequiredSkill", "RequiredSkillRank", "maxcount", "stackable", "spellid_1", "spelltrigger_1", "spellcharges_1",
    "spellcooldown_1", "spellcategory_1", "spellcategorycooldown_1", "bonding", "description", "Material", "sheath",
    "VerifiedBuild",
)
CONSUMABLE, RECIPE = 0, 9
SUB_FLASK, SUB_SCROLL, SUB_ENHANCEMENT, SUB_OTHER = 3, 4, 6, 8
SUB_FORMULA = 8
COMMON, UNCOMMON, RARE, EPIC = 1, 2, 3, 4
FLAG_HAS_LOOT, FLAG_PLAYERCAST = 0x4, 0x40
NO_BIND, BIND_ON_EQUIP = 0, 2
ON_USE, CONSUMED = 0, -1
FLASK_CATEGORY, FLASK_CATEGORY_COOLDOWN = 79, 3000  # the stock flasks' shared category
# Displays: C6 enchant scroll, Molten Core recipe, Flask of the Titans, Scroll of Strength VII, Rune of Portals,
# Strange Tarot.
DISPLAY = {"scroll": 811, "recipe": 6270, "flask": 24213, "buff_scroll": 3331, "rune": 28862, "tarot": 44704}

HEADER = """\
-- Crafting rework C7: the premium enchant items and their T1 recipe items, the new flasks, the raid buff scrolls, the
-- boss runes and the Darkmoon tarot (hand-picked `item` block ids 78800-78999, Item.dbc rows in
-- apps/dbc-tools/source/items.csv). GENERATED by apps/dbc-tools/write_crafting_consumable_items.py from
-- lib/crafting_consumables_data.py; edit the data and rerun, never this file. Their spells are declared in
-- apps/dbc-tools/source/world/crafting_consumables.py. Upsert: item_template rows are never deleted (codestyle-sql
-- not_delete).
"""


def _row(entry, cls, sub, name, display, quality, *, flags=0, sell=0, ilvl=60, req_level=0, skill=0, skill_rank=0,
         stack=20, spell=0, charges=CONSUMED, category=0, category_cd=-1, bonding=NO_BIND, description="") -> dict:
    values = (entry, cls, sub, -1, name, display, quality, flags, 1, 0, sell, 0, -1, -1, ilvl, req_level, skill,
              skill_rank, 0, stack, spell, ON_USE, charges, -1, category, category_cd, bonding, description, -1, 0, 0)
    return dict(zip(COLUMNS, values))


def item_rows() -> list[dict]:
    rows = []
    for p in T.PREMIUMS:
        rows.append(_row(p.item, CONSUMABLE, SUB_ENHANCEMENT, p.item_name, DISPLAY["scroll"], RARE,
                         flags=FLAG_PLAYERCAST, sell=20000, req_level=60, spell=p.use_spell))
        rows.append(_row(p.recipe_item, RECIPE, SUB_FORMULA, f"Formula: {p.item_name.removeprefix('Scroll of ')}",
                         DISPLAY["recipe"], EPIC, flags=FLAG_PLAYERCAST, sell=50000, skill=T.ENCHANTING,
                         skill_rank=300, stack=1, spell=p.learn_spell, bonding=BIND_ON_EQUIP,
                         description=f"Teaches you how to make a {p.item_name}."))
    for f in T.FLASKS:
        if f.sla is None:
            continue  # a stock flask item
        rows.append(_row(f.item, CONSUMABLE, SUB_FLASK, f.name, DISPLAY["flask"], COMMON, sell=1250, req_level=50,
                         spell=f.spell, category=FLASK_CATEGORY, category_cd=FLASK_CATEGORY_COOLDOWN))
    for n, s in enumerate(T.SCROLLS):
        _spell, _recipe, _sla, item = T.scroll_ids(n)
        rows.append(_row(item, CONSUMABLE, SUB_SCROLL, s.name, DISPLAY["buff_scroll"], UNCOMMON, sell=500,
                         req_level=60, spell=_spell, description=f"Copies {s.source}. Does not stack with it."))
    r = T.RUNE
    rows.append(_row(r.item, CONSUMABLE, SUB_OTHER, r.name, DISPLAY["rune"], RARE, sell=5000, req_level=60, stack=5,
                     spell=r.spell, category=T.RUNE_CATEGORY, category_cd=T.RUNE_COOLDOWN_MS,
                     description="Select the boss you want to push."))
    rows.append(_row(T.TAROT_ITEM, CONSUMABLE, SUB_OTHER, "Darkmoon Tarot", DISPLAY["tarot"], UNCOMMON,
                     flags=FLAG_HAS_LOOT, sell=2500, charges=0,
                     description="Open it to draw a card of the Beasts, Warlords, Elementals or Portals deck."))
    return sorted(rows, key=lambda r: r["entry"])


def render_sql(rows: list[dict]) -> str:
    out = [HEADER.rstrip("\n")]
    out += S._wrap_tokens([f"`{c}`" for c in COLUMNS], "INSERT INTO `item_template` (", ") VALUES")
    for index, row in enumerate(rows):
        out += S._wrap_tokens([S._sql_value(row[c]) for c in COLUMNS], "(",
                              ")" + ("," if index < len(rows) - 1 else ""))
    out += S._wrap_tokens([f"`{c}` = VALUES(`{c}`)" for c in COLUMNS[1:]], "ON DUPLICATE KEY UPDATE", ";")
    out.append("")
    out.append("-- The Darkmoon Tarot opens into one card of the four vanilla decks (group 1, equal chance).")
    out.append(f"DELETE FROM `item_loot_template` WHERE `Entry` = {T.TAROT_ITEM};")
    out += S._insert_lines("item_loot_template")
    out += S._loot_values([(T.TAROT_ITEM, card, 0, 0, 1, 1, 1, "Darkmoon Tarot: a vanilla deck card")
                           for card in T.CARDS])
    return "\n".join(out) + "\n"


def csv_rows(rows: list[dict]) -> list[str]:
    return [f"{r['entry']},{r['class']},{r['subclass']},-1,-1,{r['displayid']},0,0,"
            f"{r['name']} (crafting rework C7)" for r in rows]


def render_csv(existing: str, rows: list[dict]) -> str:
    def row_id(line: str) -> int | None:
        head = line.split(",", 1)[0]
        return int(head) if head.isdigit() else None

    out = [line for line in existing.splitlines() if row_id(line) is None or row_id(line) not in ITEM_RANGE]
    for line in csv_rows(rows):
        entry = row_id(line)
        at = next((i for i, kept in enumerate(out) if (row_id(kept) or 0) > entry), len(out))
        out.insert(at, line)
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the files are stale, write nothing")
    args = parser.parse_args()
    rows = item_rows()
    want = {SQL_PATH: render_sql(rows), ITEMS_CSV: render_csv(ITEMS_CSV.read_text(), rows)}
    stale = [p for p, text in want.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path}")
        return 1 if stale else 0
    for path, text in want.items():
        path.write_text(text)
    print(f"wrote {len(rows)} items: " + ", ".join(str(p.relative_to(REPO_ROOT)) for p in want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
