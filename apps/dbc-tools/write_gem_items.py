#!/usr/bin/env python3
"""
Crafting rework C5: writes the gem items' hand-written rows from `lib/crafting_gems_data.py`.

- `data/sql/updates/pending_db_world/rev_crafting_c5_gem_items.sql`: an `item_template` upsert for the 89 cut gems,
  the 6 epic raw gems and the 2 new raw gems, Ruby and Dusk Amethyst (item_template rows are never deleted,
  codestyle-sql not_delete);
- the matching `source/items.csv` rows (Item.dbc, so the client knows the new entries), replacing any earlier rows
  in 70720-70899.

New items are `items.csv` plus a hand-written row (registry.item_template() only edits existing items). Run it after
changing the table; `lib/test_crafting_gems.py` fails while the files and the table disagree.

    python3 write_gem_items.py [--check]
"""

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

from lib import crafting_gems_data as T  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
SQL_PATH = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c5_gem_items.sql"
ITEMS_CSV = TOOL_ROOT / "source" / "items.csv"
ITEM_RANGE = range(70720, 70900)
WIDTH = 120

COLUMNS = (
    "entry", "class", "subclass", "SoundOverrideSubclass", "name", "displayid", "Quality", "Flags", "BuyCount",
    "BuyPrice", "SellPrice", "InventoryType", "AllowableClass", "AllowableRace", "ItemLevel", "RequiredLevel",
    "maxcount", "stackable", "spellcooldown_1", "spellcategorycooldown_1", "spellcooldown_2", "spellcategorycooldown_2",
    "spellcooldown_3", "spellcategorycooldown_3", "spellcooldown_4", "spellcategorycooldown_4", "spellcooldown_5",
    "spellcategorycooldown_5", "bonding", "description", "Material", "sheath", "GemProperties", "BagFamily",
    "RequiredDisenchantSkill", "VerifiedBuild",
)
CLASS_GEM = 3
SUBCLASS_SIMPLE = 7  # stock vanilla raw gems (Star Ruby, Citrine, ...)
BAG_FAMILY_GEMS = 512
NO_SPELL_COOLDOWNS = (-1,) * 10
# Cut gems don't stack (stock: every cut gem is stackable 1): WorldSession::HandleSocketOpcode removes the socketed gem
# with DestroyItem, which deletes the whole stack. Raw gems stack to 20 like the stock raws.
CUT_GEM_STACK = 1
RAW_GEM_STACK = 20

HEADER = """\
-- Crafting rework C5: the gem items (hand-picked `item` block ids 70720-70827, Item.dbc rows in
-- apps/dbc-tools/source/items.csv). GENERATED by apps/dbc-tools/write_gem_items.py from lib/crafting_gems_data.py; edit
-- the table and rerun, never this file. Their GemProperties, enchants and Jewelcrafting cuts are declared in
-- apps/dbc-tools/source/world/crafting_gems.py.
-- Shaped like the stock cut gems (Bold Living Ruby 24027): class 3 (Gem), subclass = color, Material -1, BagFamily 512
-- (gem bags), no level requirement on the item (rare, epic and meta enchants carry MinLevel 60 instead), cut gems do
-- not stack (socketing destroys the whole stack), raw gems stack to 20, tradeable. The six epic raw gems (70820-70825)
-- have no source yet (raid drops later, user 2026-11-11). The new raws Ruby (70826) and Dusk Amethyst (70827) are
-- shaped like stock vanilla raws (subclass 7); their drops are in rev_crafting_c5_raw_gems_loot.sql. Upsert:
-- item_template rows are never deleted (codestyle-sql not_delete).
"""


def _sql_value(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    return str(value)


def _wrap_tokens(tokens: list[str], first: str, last: str, indent: str = "    ") -> list[str]:
    """Join `tokens` with ", " after `first`, breaking only between tokens, so a string literal is never split."""
    lines, current = [], first
    for index, token in enumerate(tokens):
        piece = token + ("," if index < len(tokens) - 1 else last)
        joiner = "" if current.endswith("(") else " "
        if len(current) + len(joiner) + len(piece) > WIDTH:
            lines.append(current.rstrip())
            current = indent + piece
        else:
            current += joiner + piece
    lines.append(current)
    return lines


def item_rows() -> list[dict]:
    rows = []
    for gem in T.gems():
        description = T.COLOR_TEXT[gem["color"]]
        if gem["kind"] == "meta":
            extra = next(extra for key, *_rest, extra in T.METAS if key == gem["meta_key"])
            description = extra or description
        rows.append(_row(gem["item"], T.GEM_SUBCLASS[gem["color"]], gem["name"], gem["display"], gem["quality"],
                         gem["buy"], gem["sell"], gem["item_level"], gem["gemprop"], description, CUT_GEM_STACK))
    for raw in T.epic_raws():
        rows.append(_row(raw["item"], T.GEM_SUBCLASS[raw["color"]], raw["name"], raw["display"], raw["quality"],
                         raw["buy"], raw["sell"], raw["item_level"], 0, "", RAW_GEM_STACK))
    for raw in T.new_raws():
        rows.append(_row(raw["item"], SUBCLASS_SIMPLE, raw["name"], raw["display"], raw["quality"], raw["buy"],
                         raw["sell"], raw["item_level"], 0, "", RAW_GEM_STACK))
    rows.sort(key=lambda row: row["entry"])
    return rows


def _row(entry, subclass, name, display, quality, buy, sell, item_level, gemprop, description, stack) -> dict:
    values = (entry, CLASS_GEM, subclass, -1, name, display, quality, 0, 1, buy, sell, 0, -1, -1, item_level, 0, 0, stack,
              *NO_SPELL_COOLDOWNS, 0, description, -1, 0, gemprop, BAG_FAMILY_GEMS, -1, 0)
    return dict(zip(COLUMNS, values))


def render_sql(rows: list[dict]) -> str:
    out = [HEADER.rstrip("\n")]
    out += _wrap_tokens([f"`{c}`" for c in COLUMNS], "INSERT INTO `item_template` (", ") VALUES")
    for index, row in enumerate(rows):
        out += _wrap_tokens([_sql_value(row[c]) for c in COLUMNS], "(", ")" + ("," if index < len(rows) - 1 else ""))
    out += _wrap_tokens([f"`{c}` = VALUES(`{c}`)" for c in COLUMNS[1:]], "ON DUPLICATE KEY UPDATE", ";")
    return "\n".join(out) + "\n"


def csv_rows(rows: list[dict]) -> list[str]:
    return [f"{r['entry']},{CLASS_GEM},{r['subclass']},-1,-1,{r['displayid']},0,0,{r['name']} (crafting rework C5 gem)"
            for r in rows]


def render_csv(existing: str, rows: list[dict]) -> str:
    """`existing` with this writer's rows replaced: each new row goes before the first kept row with a higher id, so
    the gem and enchant writers (crafting rework C5 / C6) leave each other's blocks in id order whichever runs last."""
    def row_id(line: str) -> int | None:
        head = line.split(",", 1)[0]
        return int(head) if head.isdigit() else None

    out = [line for line in existing.splitlines() if row_id(line) is None or row_id(line) not in ITEM_RANGE]
    for line in csv_rows(rows):
        entry = row_id(line)
        at = next((i for i, kept in enumerate(out) if (row_id(kept) or 0) > entry), len(out))
        out.insert(at, line)
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the files are stale, write nothing")
    args = parser.parse_args()
    rows = item_rows()
    want_sql = render_sql(rows)
    want_csv = render_csv(ITEMS_CSV.read_text(), rows)
    stale = [p for p, want in ((SQL_PATH, want_sql), (ITEMS_CSV, want_csv)) if not p.exists() or p.read_text() != want]
    if args.check:
        for path in stale:
            print(f"stale: {path}")
        return 1 if stale else 0
    SQL_PATH.write_text(want_sql)
    ITEMS_CSV.write_text(want_csv)
    print(f"wrote {len(rows)} items: {SQL_PATH.relative_to(REPO_ROOT)}, {ITEMS_CSV.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
