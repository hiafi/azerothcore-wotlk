#!/usr/bin/env python3
"""
Crafting rework C7: writes the recipe retirement's hand-written SQL from `lib/crafting_retire_data.py` (decision 1 of
`.agents/plans/crafting-rework/crafting-rework.C7-RESEARCH.md`). The spell-side half (untrain, starter recipes, the
recipe items' template) is declared in `source/world/crafting_retire.py`.

- `data/sql/updates/pending_db_world/rev_crafting_c7_retire.sql`:
  - the retired recipe items leave every loot table (their own rows, not references), every vendor (event vendors
    included) and the conditions on those rows;
  - `disables` refuses the retired recipe spells for players (sourceType 0, flag 1). The learn guard in
    `custom_professions.cpp` reads it: a profession recipe disabled for players can't be learned (1d A);
  - `disables` turns off the quests that rewarded a retired recipe (sourceType 1; decision 1e, kept for later).
- `data/sql/updates/pending_db_characters/rev_crafting_c7_retire_learned.sql`: deletes the retired recipes from
  `character_spell` (bots included). Apply with the worldserver stopped (the normal deploy order).

Run it after changing the data; `lib/test_crafting_retire.py` fails while the files and the data disagree.

    python3 write_crafting_retire.py [--check]
"""

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

from lib import crafting_retire_data as R  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
WORLD_SQL = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c7_retire.sql"
CHARACTERS_SQL = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_characters" / "rev_crafting_c7_retire_learned.sql"
WIDTH = 120

# Every loot table a recipe item drops from as an item row (`Reference` = 0); reference pools keep their own entry.
LOOT_TABLES = (
    "creature_loot_template", "gameobject_loot_template", "item_loot_template", "reference_loot_template",
    "pickpocketing_loot_template", "fishing_loot_template", "skinning_loot_template",
)
# conditions.SourceTypeOrReferenceId of those loot tables (SourceEntry = the item), and of npc_vendor (23).
CONDITION_SOURCE_TYPES = (1, 3, 4, 5, 8, 10, 11, 23)
DISABLE_TYPE_SPELL, DISABLE_TYPE_QUEST = 0, 1
SPELL_DISABLE_PLAYER = 0x1

WORLD_HEADER = """\
-- Crafting rework C7: recipe retirement (.agents/plans/crafting-rework/crafting-rework.C7-RESEARCH.md decision 1,
-- ruled 2026-11-12). GENERATED by apps/dbc-tools/write_crafting_retire.py from lib/crafting_retire_data.py; edit the
-- data and rerun, never this file. The trainer rows, starter recipes and the recipe items' template (no teach spell,
-- Poor quality) are in the generated rev from source/world/crafting_retire.py.
"""

CHARACTERS_HEADER = """\
-- Crafting rework C7: the retired recipes leave every character's spellbook, bots included (decision 1d A). Apply
-- with the worldserver stopped. GENERATED by apps/dbc-tools/write_crafting_retire.py from
-- lib/crafting_retire_data.py; edit the data and rerun, never this file.
"""


def wrap_ids(prefix: str, ids, suffix: str) -> list[str]:
    """`prefix` + `(a, b, ...)` + `suffix`, wrapped at value boundaries to WIDTH, continuation lines indented 4."""
    parts = [str(i) for i in sorted(ids)]
    lines, line = [], prefix + "("
    for n, part in enumerate(parts):
        token = part + (", " if n < len(parts) - 1 else ")" + suffix)
        if len(line) + len(token.rstrip()) > WIDTH:
            lines.append(line.rstrip())
            line = "    "
        line += token
    lines.append(line)
    return lines


def sql_string(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "''") + "'"


def disable_rows(source_type: int, flags: int, entries: dict[int, str]) -> list[str]:
    rows = []
    for n, (entry, comment) in enumerate(sorted(entries.items())):
        end = ";" if n == len(entries) - 1 else ","
        rows.append(f"({source_type}, {entry}, {flags}, '', '', {sql_string(comment)}){end}")
    return rows


def world_sql() -> str:
    items = list(R.RECIPE_ITEMS)
    out = [WORLD_HEADER]
    out.append(f"-- The {len(items)} retired recipe items leave every loot table, vendor and their conditions.")
    for table in LOOT_TABLES:
        out += wrap_ids(f"DELETE FROM `{table}` WHERE `Reference` = 0 AND `Item` IN ", items, ";")
    out += wrap_ids("DELETE FROM `npc_vendor` WHERE `item` IN ", items, ";")
    out += wrap_ids("DELETE FROM `game_event_npc_vendor` WHERE `item` IN ", items, ";")
    types = ", ".join(map(str, CONDITION_SOURCE_TYPES))
    out += wrap_ids(f"DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` IN ({types}) AND `SourceEntry` IN ",
                    items, ";")
    out.append("")
    out.append(f"-- The {len(R.RETIRED)} retired recipes are refused to players: no craft, and the learn guard in")
    out.append("-- custom_professions.cpp refuses to teach a profession recipe disabled for players.")
    spells = {s: f"Crafting C7: retired recipe, {prof} - {name}" for s, (prof, name, _) in R.RETIRED.items()}
    out += wrap_ids(f"DELETE FROM `disables` WHERE `sourceType` = {DISABLE_TYPE_SPELL} AND `entry` IN ", spells, ";")
    out.append(f"DELETE FROM `disables` WHERE `sourceType` = {DISABLE_TYPE_SPELL} AND `comment` LIKE "
               "'Crafting C7: retired recipe%';")
    out.append("INSERT INTO `disables` (`sourceType`, `entry`, `flags`, `params_0`, `params_1`, `comment`) VALUES")
    out += disable_rows(DISABLE_TYPE_SPELL, SPELL_DISABLE_PLAYER, spells)
    out.append("")
    out.append(f"-- The {len(R.DISABLED_QUESTS)} quests that rewarded a retired recipe are off for now (decision 1e:")
    out.append("-- kept as candidates for the later recipe quests).")
    quests = {q: f"Crafting C7: rewarded a retired recipe ({title})"
              for q, title in R.DISABLED_QUESTS.items()}
    out += wrap_ids(f"DELETE FROM `disables` WHERE `sourceType` = {DISABLE_TYPE_QUEST} AND `entry` IN ", quests, ";")
    out.append(f"DELETE FROM `disables` WHERE `sourceType` = {DISABLE_TYPE_QUEST} AND `comment` LIKE "
               "'Crafting C7: rewarded a retired recipe%';")
    out.append("INSERT INTO `disables` (`sourceType`, `entry`, `flags`, `params_0`, `params_1`, `comment`) VALUES")
    out += disable_rows(DISABLE_TYPE_QUEST, 0, quests)
    return "\n".join(out) + "\n"


def characters_sql() -> str:
    out = [CHARACTERS_HEADER]
    out += wrap_ids("DELETE FROM `character_spell` WHERE `spell` IN ", R.RETIRED, ";")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the files differ from the data, write nothing")
    args = parser.parse_args()
    stale = []
    for path, text in ((WORLD_SQL, world_sql()), (CHARACTERS_SQL, characters_sql())):
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(text)
    if args.check and stale:
        print("stale: " + ", ".join(str(p.relative_to(REPO_ROOT)) for p in stale))
        return 1
    if not args.check:
        print("wrote " + (", ".join(str(p.relative_to(REPO_ROOT)) for p in stale) or "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
