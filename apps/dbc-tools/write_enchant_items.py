#!/usr/bin/env python3
"""
Crafting rework C6: writes the enchant items' hand-written rows from `lib/crafting_enchants_data.py`.

- `data/sql/updates/pending_db_world/rev_crafting_c6_enchant_items.sql`: an `item_template` upsert for the 116 basic
  enchant items (leveling and endgame), the 4 Engineering tinkers and the belt buckle (item_template rows are never
  deleted, codestyle-sql not_delete);
- the matching `source/items.csv` rows (Item.dbc, so the client knows the new entries), replacing any earlier rows
  in 79000-79199.

New items are `items.csv` plus a hand-written row (registry.item_template() only edits existing items). Run it after
changing the table; `lib/test_crafting_enchants.py` fails while the files and the table disagree.

    python3 write_enchant_items.py [--check]
"""

import argparse
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_ROOT))

from lib import crafting_enchants_data as T  # noqa: E402

REPO_ROOT = TOOL_ROOT.parent.parent
SQL_PATH = REPO_ROOT / "data" / "sql" / "updates" / "pending_db_world" / "rev_crafting_c6_enchant_items.sql"
ITEMS_CSV = TOOL_ROOT / "source" / "items.csv"
ITEM_RANGE = range(79000, 79200)
WIDTH = 120

COLUMNS = (
    "entry", "class", "subclass", "SoundOverrideSubclass", "name", "displayid", "Quality", "Flags", "BuyCount",
    "BuyPrice", "SellPrice", "InventoryType", "AllowableClass", "AllowableRace", "ItemLevel", "RequiredLevel",
    "maxcount", "stackable", "spellid_1", "spelltrigger_1", "spellcharges_1", "spellcooldown_1", "spellcategory_1",
    "spellcategorycooldown_1", "spellcooldown_2", "spellcategorycooldown_2", "spellcooldown_3",
    "spellcategorycooldown_3", "spellcooldown_4", "spellcategorycooldown_4", "spellcooldown_5",
    "spellcategorycooldown_5", "bonding", "description", "Material", "sheath", "BagFamily", "RequiredDisenchantSkill",
    "VerifiedBuild",
)
CLASS_CONSUMABLE = 0
SUBCLASS_ITEM_ENHANCEMENT = 6  # the stock kits, spellthreads, buckles and enchanting scrolls
ITEM_FLAG_PLAYERCAST = 0x40  # the stock kits' Flags
STACK = 20
SPELLTRIGGER_ON_USE = 0
CHARGES_CONSUMED = -1  # one used per application
OTHER_SPELL_COOLDOWNS = (-1,) * 8

HEADER = """\
-- Crafting rework C6: the enchant items (hand-picked `item` block ids 79000-79130, Item.dbc rows in
-- apps/dbc-tools/source/items.csv). GENERATED by apps/dbc-tools/write_enchant_items.py from
-- lib/crafting_enchants_data.py; edit the table and rerun, never this file. Their enchants, on-use spells and recipes
-- are declared in apps/dbc-tools/source/world/crafting_enchants.py.
-- Shaped like the stock kits and spellthreads (Rugged Armor Kit 15564, Brilliant Spellthread 41602): class 0
-- subclass 6 (Item Enhancement), the use spell's item cursor picks the gear piece, one used per application, stack 20,
-- tradeable (anyone can apply them, R25). Leveling set: Common, item level 30, no level requirement; endgame set,
-- tinkers and buckle: Uncommon, item level 60, required level 60 (the enchants carry MinLevel 60 too). Upsert:
-- item_template rows are never deleted (codestyle-sql not_delete).
"""


def _sql_value(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    return str(value)


def _wrap_tokens(tokens: list[str], first: str, last: str, indent: str = "    ") -> list[str]:
    """Join `tokens` with ", " after `first`, breaking only between tokens, so a string literal is never split."""
    lines, current = [], first
    for index, token in enumerate(tokens):
        piece = token + ("," if index < len(tokens) - 1 else last)
        joiner = "" if current.endswith("(") else " "
        if len(current) + len(joiner) + len(piece) > WIDTH:
            lines.append(current.rstrip())
            current = indent + piece
        else:
            current += joiner + piece
    lines.append(current)
    return lines


def item_rows() -> list[dict]:
    return [_row(item) for item in T.items()]


def _row(item: dict) -> dict:
    values = (item["item"], CLASS_CONSUMABLE, SUBCLASS_ITEM_ENHANCEMENT, -1, item["name"], item["display"],
              item["quality"], ITEM_FLAG_PLAYERCAST, 1, item["buy"], item["sell"], 0, -1, -1, item["item_level"],
              item["required_level"], 0, STACK, item["use_spell"], SPELLTRIGGER_ON_USE, CHARGES_CONSUMED, -1, 0, -1,
              *OTHER_SPELL_COOLDOWNS, 0, "", -1, 0, 0, -1, 0)
    return dict(zip(COLUMNS, values))


def render_sql(rows: list[dict]) -> str:
    out = [HEADER.rstrip("\n")]
    out += _wrap_tokens([f"`{c}`" for c in COLUMNS], "INSERT INTO `item_template` (", ") VALUES")
    for index, row in enumerate(rows):
        out += _wrap_tokens([_sql_value(row[c]) for c in COLUMNS], "(", ")" + ("," if index < len(rows) - 1 else ""))
    out += _wrap_tokens([f"`{c}` = VALUES(`{c}`)" for c in COLUMNS[1:]], "ON DUPLICATE KEY UPDATE", ";")
    return "\n".join(out) + "\n"


def csv_rows(rows: list[dict]) -> list[str]:
    return [f"{r['entry']},{CLASS_CONSUMABLE},{SUBCLASS_ITEM_ENHANCEMENT},-1,-1,{r['displayid']},0,0,"
            f"{r['name']} (crafting rework C6 enchant item)" for r in rows]


def render_csv(existing: str, rows: list[dict]) -> str:
    """`existing` with this writer's rows replaced: each new row goes before the first kept row with a higher id, so
    the gem and enchant writers (crafting rework C5 / C6) leave each other's blocks in id order whichever runs last."""
    def row_id(line: str) -> int | None:
        head = line.split(",", 1)[0]
        return int(head) if head.isdigit() else None

    out = [line for line in existing.splitlines() if row_id(line) is None or row_id(line) not in ITEM_RANGE]
    for line in csv_rows(rows):
        entry = row_id(line)
        at = next((i for i, kept in enumerate(out) if (row_id(kept) or 0) > entry), len(out))
        out.insert(at, line)
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the files are stale, write nothing")
    args = parser.parse_args()
    rows = item_rows()
    want_sql = render_sql(rows)
    want_csv = render_csv(ITEMS_CSV.read_text(), rows)
    stale = [p for p, want in ((SQL_PATH, want_sql), (ITEMS_CSV, want_csv)) if not p.exists() or p.read_text() != want]
    if args.check:
        for path in stale:
            print(f"stale: {path}")
        return 1 if stale else 0
    SQL_PATH.write_text(want_sql)
    ITEMS_CSV.write_text(want_csv)
    print(f"wrote {len(rows)} items: {SQL_PATH.relative_to(REPO_ROOT)}, {ITEMS_CSV.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
