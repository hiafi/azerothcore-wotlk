-- Item variants IV0b: shield armor curve.
--
-- Shields (armor subclass 6, InventoryType 14) had no item_armor_curve rows, so ItemBudget.cpp left their stored
-- `armor` alone (itemization-changes.md 9.3a, Scope) and a heroic copy of a level 20 shield would have kept level 20
-- armor. This adds the missing curve; the C++ (ItemBudget.cpp, keyed on item_template.SubClass) and
-- apps/item-tools/item_lib/budget.py need no change.
--
-- item_armor_curve (ilvl, 6): shield armor as an "Epic-equivalent" value, ilvl 1-300, same method as the other four
-- classes (itemization-changes.md 9.3a): sample-size-weighted isotonic regression (pool-adjacent-violators) over every
-- real shield (entry <= 56806, Poor-Epic, armor > 0, monster/test/deprecated rows dropped). Each shield's base armor
-- (item_template.armor minus ArmorDamageModifier, which the C++ adds back) is divided by the shared
-- item_armor_quality_mult first, so one curve serves every quality; Epic samples weigh 3x so the curve tracks the
-- quality that dungeon heroics mint (Epic at ilvl 60-70). Linear interpolation between observed ilvls, linear
-- extrapolation below ilvl 11 (the Uncommon+ data starts there; Poor/Common reach ilvl 1) and above ilvl 277 at the
-- slope of the last observed segment (30.1/ilvl, the way the plate curve keeps rising past its data). Unlike the
-- other classes this fit is not Chest/Robe-only and PvP season shields stay in: shield armor depends on ilvl and
-- quality only (a Gladiator's shield sits on the same line as a PvE shield of that ilvl).
--
-- item_armor_slot_mult (14 = Shield): 1.0, the curve is already in shield units.
--
-- baseline_armor = round(curve(ilvl, 6) * 1.0 * item_armor_quality_mult(quality)); Epic 66 = 2857, Rare 66 = 2294.
--
-- Known limit: the quality multiplier is shared with the armor classes. Vanilla and Outland shields follow it to
-- within a few percent, but WotLK Rare shields (ilvl 130+) carry 8-14% more armor than Rare x 0.803.
--
