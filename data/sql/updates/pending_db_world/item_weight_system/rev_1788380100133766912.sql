--
-- Phase 5 prep: populate item_weapon_dps_curve so weapons can be included
-- in the itemization-changes.md §4.5 conversion pass (docs/itemization-
-- changes.md's Phase 5). Until now this table was empty and any
-- item_budget_assign row on a weapon would fail validation (ItemBudget.cpp
-- logs "no item_weapon_dps_curve entry" and leaves the item unmaterialized).
--
-- Methodology mirrors the item_budget_curve/item_armor_curve derivation:
-- for every live Rare/Epic weapon (item_template class=2, Quality IN (3,4),
-- Delay>0, dmg_max1>0), computed per-item DPS = avg(dmg_min1,dmg_max1) /
-- (Delay/1000), took the median DPS per (ItemLevel, Quality) cell, then fit
-- a weighted (weight = sample count) isotonic regression (PAVA) per quality
-- line to enforce DPS non-decreasing with ilvl, then linearly interpolated/
-- extrapolated across the full ilvl 1-300 range (matching every other
-- curve table's coverage). Real weapon data covered Rare ilvl 5-200 (1096
-- samples, 83 distinct ilvls) and Epic ilvl 40-284 (1367 samples, 76
-- distinct ilvls); everything outside those ranges is extrapolated from
-- the nearest fitted segment's slope, same as the original stat/armor
-- curves' treatment of sparse ilvls.
--
-- Fidelity against real per-item DPS: mean |deviation| 18.4%, median 12.4%,
-- 43% of items within +/-10%, 64% within +/-20% -- comparable to the
-- pre-revision-3 stat budget curve's fit quality (real weapon DPS scatters
-- more than armor stat totals because dagger/fast-weapon vs 2H/slow-weapon
-- itemization diverges more at a given ilvl than this single (ilvl,
-- quality) axis can capture; there's no per-subclass column in this
-- table's schema to correct for that).
--
-- At 20 of 300 ilvls the two independently-fit lines crossed (Epic
-- dipping below Rare by up to ~0.3 dps, all clustered right where the two
-- quality's real data ranges barely overlap, ilvl 56-66 and ~150) --
-- clamped Epic to floor at Rare's value there so Epic never DPS-loses to
-- Rare at the same ilvl, consistent with item_quality_mult's Epic >= Rare
-- ordering (1.0 vs 0.9) for the stat budget.
--
-- item_weapon_dps_spread: also updated from its Phase-1 placeholder (0.3,
-- the ItemBudget.cpp code-side fallback) to 0.6 -- the median (Delay-
-- normalized) (dmg_max1-dmg_min1)/avgDamage ratio measured across the same
-- 2451-item Rare/Epic sample (mean 0.573, median 0.601, consistent between
-- qualities). item_weapon_dps_cost is left at its existing placeholder
-- (1.0 budget point per DPS point of dps_delta) -- no item in this pass
-- uses dps_delta yet, so there's no data to derive a better value from.
--

