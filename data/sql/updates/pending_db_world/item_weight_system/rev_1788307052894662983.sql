--
-- Percentage-allocation itemization system: item_stamina_curve.
-- See docs/itemization-changes.md §3, §9.3. Resolves a gap in the original
-- design (StaminaCurve was referenced but never given a table or formula).
--
-- baseline_stamina = StaminaCurve(ilvl) * SlotMult(inv_type) * QualityMult(quality)
--
-- Derivation: same method as item_budget_curve (§4.5) -- median normalized
-- stamina per item level among Epic armor (same 14 known-bad entries
-- excluded), sample-size-weighted isotonic regression, ilvl 219 excluded
-- from the fit as confirmed catch-up gear, linear interpolation/extrapolation
-- for ilvl 1-300.
--
-- Revision 2 (replaces the original fit): now additionally folds in
-- on-equip passive spell effects (SPELL_AURA_MOD_STAT with misc=stamina),
-- resolved from the client's Spell.dbc -- see item_budget_curve's revision-2
-- note for the full methodology and why it changed alongside this table.
-- The two curves come from the same regression pass and must be reloaded
-- together; item_budget_curve now strictly excludes stamina, so a stale
-- copy of either table reintroduces the double-count both were fixing.
--

CREATE TABLE IF NOT EXISTS `item_stamina_curve` (
  `ilvl` smallint unsigned NOT NULL,
  `stamina` int unsigned NOT NULL,
  PRIMARY KEY (`ilvl`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Off-budget stamina by item level, before SlotMult/QualityMult';

