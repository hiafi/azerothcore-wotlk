-- Permafrost (200015) playtest bugfix, user-confirmed tuning (2026-08-26):
--
-- Live A/B test (7x Ice Lance at 5 stacks vs. 7x at 0 stacks) came back statistically identical
-- (125 vs 123 average damage) despite the damage-bonus code path tracing out correctly end to end.
-- Root cause: the stack buff's duration was only 3 sec (DurationIndex 27), a first-pass guess
-- flagged in mage_talents.csv's own notes as unconfirmed. Since a stack only refreshes while the
-- caster is actively moving, stopping to actually cast Ice Lance a few times let the whole bank
-- decay to 0 well before the 7-cast sample finished, diluting the bonus down to noise.
--
-- Bumped to 10 sec (DurationIndex 1, matches the existing stock 10000ms row - no new SpellDuration
-- row needed). Consumption also moved from spending 1 stack per Ice Lance cast to clearing the
-- entire bank in one cast, with the damage bonus now scaling per stack consumed (20% * stack
-- count) instead of a flat 20% regardless of banked count - see spell_mage.cpp
-- (spell_mage_ice_lance::ConsumePermafrost) and MageMechanics.cpp
-- (Mage::ApplyDoneDamagePctMods) for the accompanying code change.
UPDATE `spell_dbc` SET `DurationIndex` = 1 WHERE `ID` = 200015 AND `DurationIndex` = 27;
