-- Root cause of "Evocation isn't restoring mana", found via live engine-level debug logging
-- (2026-08-26/27): Permafrost (12571) and Chilled to the Bone (44568) each have a SPELLMOD_EFFECT1
-- (-10 flat) modifier meant to scope only to Frostbolt/Cone of Cold (classmask 544), but that
-- modifier's classmask was landing empty at runtime - Player::ApplySpellMod's classmask check
-- (SpellInfo::IsAffected) treats an all-zero classmask as "matches every spell in the family"
-- (SpellInfo.cpp), so both mods were unconditionally applying -10/-10 to every mage spell's
-- EFFECT_0, including Evocation's mana-restore percentage (15% -> -5%, i.e. 0% after the engine's
-- own `std::max(amount, 0)` floor - AuraEffect::HandleObsModPowerAuraTick).
--
-- The actual bug: `spell_dbc`'s 9 EffectSpellClassMask{A,B,C}_{1,2,3} columns are physically
-- consumed in DECLARATION order (A_1,A_2,A_3,B_1,B_2,B_3,C_1,C_2,C_3 - confirmed against
-- data/sql/base/db_world/spell_dbc.sql's CREATE TABLE) and packed sequentially into the engine's
-- `std::array<flag96, 3> EffectSpellClassMask` (DBCStructure.h) - which is EFFECT-major, not
-- dword-major. That makes column "N" of letter-group X actually land in Effects[X-as-index]'s
-- dword N, not Effects[N-1]'s dword X as the "_1/_2/_3 = effect index" naming convention used by
-- every *other* per-effect field in this schema (EffectBasePoints_1/2/3, EffectAura_1/2/3, ...)
-- would suggest. Confirmed empirically: logging AuraEffect::CalculateSpellMod's actual computed
-- `mask` showed Effects[0]=(544,544,0) and Effects[1]=(0,0,0) for both rows, even though the
-- *_1/_2/_3-as-effect-index reading of the raw columns (EffectSpellClassMaskA_1=544/0,
-- EffectSpellClassMaskA_2=544 for both) looked like a normal, correctly-scoped pair.
--
-- This looks like a systemic mismatch, not something specific to these two rows - a search of
-- apps/dbc-tools/source/spells/mage_talents.csv alone turns up 60+ other "_2"/"_3"-suffixed
-- EffectSpellClassMask overrides (many on "pulled from existing data" rows, i.e. predating the
-- frost mage rework entirely), any of which could have the exact same transpose. NOT attempting a
-- blanket fix here - that needs a dedicated audit of the DBC build pipeline itself (whichever side
-- is "wrong": how the original bulk pull wrote these columns, or how dbcfmt.py documents them) and
-- is well out of scope for a live-playtest bugfix. This migration only corrects the rows actually
-- checked and confirmed to have the same broken pattern (EffectMiscValue_2=3,
-- EffectSpellClassMaskA_2=544, EffectSpellClassMaskB_1=0) - all 3 ranks of both Permafrost
-- (11175/12569/12571) and Chilled to the Bone (44566/44567/44568), not just the rank-3 capstones
-- that happened to be equipped on the test character that surfaced this. Moves each row's
-- Frostbolt|Cone of Cold classmask (544) off of the wrong column (EffectSpellClassMaskA_2, which
-- the engine reads as Effects[0]'s *second* dword) onto the column the engine actually reads as
-- Effects[1]'s first dword (EffectSpellClassMaskB_1).
UPDATE `spell_dbc` SET `EffectSpellClassMaskA_2` = 0, `EffectSpellClassMaskB_1` = 544
WHERE `ID` IN (11175, 12569, 12571, 44566, 44567, 44568)
  AND `EffectSpellClassMaskA_2` = 544 AND `EffectSpellClassMaskB_1` = 0;
