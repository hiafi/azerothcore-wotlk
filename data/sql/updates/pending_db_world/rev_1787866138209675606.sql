-- Shattering Cold (200003): fix silent SPELL_FAILED_OUT_OF_RANGE on every Flurry cast
-- (playtest bug, 2026-08-27). range_yards was left null on this row, which
-- apps/dbc-tools/lib/reuse.py's range_index() maps to RangeIndex 0 for "unset" - but unlike
-- SpellDuration.dbc's ID 0 (see the Icicles fix, rev_1787824460460102849.sql), the real client's
-- SpellRange.dbc *does* have a row 0, and it isn't "unlimited": it's a near-zero/self-only range.
-- Spell.cpp's CheckCast only special-cases RangeEntry->ID == 1 to skip the range check entirely
-- for triggered 0-range spells ("check needed by 68766 51693... triggered by other spells"), not
-- ID 0. So every spell_mage_flurry::ApplyShatteringCold's caster->CastSpell(target, 200003, true)
-- (spell_mage.cpp) against the (non-self) target dummy silently failed SPELL_FAILED_OUT_OF_RANGE -
-- confirmed live via temporary LOG_ERROR tracing (CastSpell returned 97 = SPELL_FAILED_OUT_OF_RANGE,
-- HasAura false immediately after). RangeIndex 5 is the stock client's existing 40yd row, matching
-- Flurry's own range (200004) since Shattering Cold can only ever be triggered on whatever Flurry
-- already hit - not a minted row, so no `spellrange_dbc` overlay insert is needed. Source of truth:
-- apps/dbc-tools/source/spells/mage.csv (range_yards 40 on the Shattering Cold row, id 200003).
-- The `RangeIndex` = 0 guard makes this a no-op on a second run.
UPDATE `spell_dbc` SET `RangeIndex` = 5 WHERE `ID` = 200003 AND `RangeIndex` = 0;
